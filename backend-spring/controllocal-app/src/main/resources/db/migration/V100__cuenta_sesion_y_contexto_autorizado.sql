CREATE TABLE sesion_acceso (
    id_sesion_acceso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia_hash VARCHAR(64) NOT NULL UNIQUE,
    semilla_contextos VARCHAR(64) NOT NULL,
    id_cuenta_acceso BIGINT NOT NULL REFERENCES cuenta_acceso(id_cuenta_acceso),
    revision BIGINT NOT NULL CHECK(revision>0),
    creada_en TIMESTAMPTZ NOT NULL,
    emitida_en TIMESTAMPTZ NOT NULL,
    vence_en TIMESTAMPTZ NOT NULL CHECK(vence_en>emitida_en),
    revocada BOOLEAN NOT NULL DEFAULT FALSE,
    id_usuario_organizacion BIGINT,
    id_persona_rol BIGINT REFERENCES persona_rol(id_persona_rol),
    rol_efectivo VARCHAR(24),
    contexto_ref_hash VARCHAR(64),
    CONSTRAINT fk_sesion_pertenencia FOREIGN KEY(id_cuenta_acceso,id_usuario_organizacion)
       REFERENCES usuario_organizacion(id_usuario,id_usuario_organizacion),
    CONSTRAINT ck_sesion_contexto CHECK (
      (id_usuario_organizacion IS NULL AND id_persona_rol IS NULL AND rol_efectivo IS NULL AND contexto_ref_hash IS NULL)
      OR (id_usuario_organizacion IS NOT NULL AND id_persona_rol IS NOT NULL
          AND rol_efectivo IN ('AGENTE','BROKER','TENANT_ADMIN') AND contexto_ref_hash IS NOT NULL)),
    CONSTRAINT ck_sesion_huellas CHECK(referencia_hash ~ '^[0-9a-f]{64}$' AND semilla_contextos ~ '^[0-9a-f]{64}$'
       AND (contexto_ref_hash IS NULL OR contexto_ref_hash ~ '^[0-9a-f]{64}$'))
);
CREATE INDEX ix_sesion_cuenta ON sesion_acceso(id_cuenta_acceso) WHERE NOT revocada;
-- Los escritores SQL también invalidan la versión anterior. JPA ya la incrementa una vez.
CREATE FUNCTION versionar_intervalo_de_pertenencia() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE ahora TIMESTAMPTZ:=clock_timestamp();
BEGIN
    IF TG_OP='INSERT' THEN
        IF NEW.alta_real_en IS NULL THEN NEW.alta_real_en:=ahora; END IF;
        IF NEW.estado='I' AND NEW.baja_real_en IS NULL THEN NEW.baja_real_en:=ahora; END IF;
    ELSIF OLD.estado IS DISTINCT FROM NEW.estado OR OLD.rol IS DISTINCT FROM NEW.rol
        OR OLD.administrar IS DISTINCT FROM NEW.administrar OR OLD.id_persona IS DISTINCT FROM NEW.id_persona
        OR OLD.id_usuario IS DISTINCT FROM NEW.id_usuario OR OLD.organizacion_id IS DISTINCT FROM NEW.organizacion_id THEN
        IF NEW.version<=OLD.version THEN NEW.version:=OLD.version+1; END IF;
        IF OLD.estado='A' AND NEW.estado='I' AND NEW.baja_real_en IS NULL THEN NEW.baja_real_en:=ahora; END IF;
        IF OLD.estado='I' AND NEW.estado='A' THEN
            IF NEW.alta_real_en IS NOT DISTINCT FROM OLD.alta_real_en THEN NEW.alta_real_en:=ahora; END IF;
            NEW.baja_real_en:=NULL;
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tg_pertenencia_versiona BEFORE INSERT OR UPDATE ON usuario_organizacion
 FOR EACH ROW EXECUTE FUNCTION versionar_intervalo_de_pertenencia();
CREATE FUNCTION revocar_sesion_por_cambio_de_pertenencia() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE sesion_acceso SET revocada=TRUE,revision=revision+1
      WHERE id_usuario_organizacion=OLD.id_usuario_organizacion AND NOT revocada;
    RETURN NEW;
END $$;
CREATE TRIGGER tg_pertenencia_revoca_sesion AFTER UPDATE ON usuario_organizacion
    FOR EACH ROW WHEN(OLD.estado IS DISTINCT FROM NEW.estado OR OLD.rol IS DISTINCT FROM NEW.rol
      OR OLD.administrar IS DISTINCT FROM NEW.administrar OR OLD.id_persona IS DISTINCT FROM NEW.id_persona
      OR OLD.id_usuario IS DISTINCT FROM NEW.id_usuario OR OLD.organizacion_id IS DISTINCT FROM NEW.organizacion_id)
    EXECUTE FUNCTION revocar_sesion_por_cambio_de_pertenencia();

-- Mismo invariante de V37, ahora sobre capacidad administrativa separada y cuenta global.
-- Cada mutación global del factor/credencial comprueba todos sus espacios, sin conceder autoridad.
CREATE OR REPLACE FUNCTION exigir_administrador_operativo() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE org BIGINT; afectadas BIGINT[]; cuenta BIGINT; exige_mfa BOOLEAN; empresarial BOOLEAN; hoy DATE;
BEGIN
    IF TG_TABLE_NAME='organizacion' THEN
        afectadas:=ARRAY[COALESCE(NEW.id_organizacion,OLD.id_organizacion)];
    ELSIF TG_TABLE_NAME IN ('usuario_organizacion','persona','persona_rol','supervision_agente') THEN
        afectadas:=ARRAY[CASE WHEN TG_OP<>'DELETE' THEN NEW.organizacion_id END,
                         CASE WHEN TG_OP<>'INSERT' THEN OLD.organizacion_id END];
    ELSE
        IF TG_TABLE_NAME='cuenta_acceso' THEN cuenta:=COALESCE(NEW.id_cuenta_acceso,OLD.id_cuenta_acceso);
        ELSE cuenta:=COALESCE(NEW.id_cuenta_acceso,OLD.id_cuenta_acceso); END IF;
        SELECT array_agg(DISTINCT organizacion_id ORDER BY organizacion_id) INTO afectadas
          FROM usuario_organizacion WHERE id_usuario=cuenta;
    END IF;
    FOR org IN SELECT DISTINCT x FROM unnest(afectadas) x WHERE x IS NOT NULL ORDER BY x LOOP
        SELECT mfa_gobierno_exigido,(modalidad='EMPRESARIAL' AND estado='A') INTO exige_mfa,empresarial
          FROM organizacion WHERE id_organizacion=org FOR UPDATE;
        hoy:=(clock_timestamp() AT TIME ZONE 'America/Lima')::date;
        IF NOT COALESCE(empresarial,FALSE) THEN CONTINUE; END IF;
        IF empresarial AND NOT EXISTS(SELECT 1 FROM usuario_organizacion u
             JOIN cuenta_acceso c ON c.id_cuenta_acceso=u.id_usuario AND c.estado='A' AND c.correo_confirmado_en IS NOT NULL
             JOIN persona p ON p.id_persona=u.id_persona AND p.organizacion_id=u.organizacion_id AND p.estado='A'
             JOIN persona_rol r ON r.id_persona=p.id_persona AND r.organizacion_id=u.organizacion_id
               AND r.tipo_rol='BROKER' AND r.vigencia_hasta IS NULL AND r.vigencia_desde<=hoy
           WHERE u.organizacion_id=org AND u.estado='A' AND u.rol='BROKER') THEN
            RAISE EXCEPTION 'Una organizacion empresarial activa requiere un broker vigente (organizacion %)',org
              USING ERRCODE='integrity_constraint_violation';
        END IF;
        IF empresarial AND EXISTS(SELECT 1 FROM usuario_organizacion u WHERE u.organizacion_id=org
             AND u.estado='A' AND u.rol='AGENTE' AND NOT EXISTS(
               SELECT 1 FROM persona_rol ra JOIN supervision_agente s ON s.id_rol_agente=ra.id_persona_rol
                 AND s.organizacion_id=org AND s.fecha_fin IS NULL
               JOIN persona_rol rb ON rb.id_persona_rol=s.id_rol_broker AND rb.organizacion_id=org
                 AND rb.tipo_rol='BROKER' AND rb.vigencia_hasta IS NULL AND rb.vigencia_desde<=hoy
               JOIN usuario_organizacion b ON b.id_persona=rb.id_persona AND b.organizacion_id=org
                 AND b.estado='A' AND b.rol='BROKER'
               JOIN cuenta_acceso c ON c.id_cuenta_acceso=b.id_usuario AND c.estado='A' AND c.correo_confirmado_en IS NOT NULL
               WHERE ra.id_persona=u.id_persona AND ra.organizacion_id=org AND ra.tipo_rol='AGENTE'
                 AND ra.vigencia_hasta IS NULL AND ra.vigencia_desde<=hoy)) THEN
            RAISE EXCEPTION 'Cada agente empresarial activo requiere un broker competente (organizacion %)',org
              USING ERRCODE='integrity_constraint_violation';
        END IF;
        IF NOT EXISTS(SELECT 1 FROM usuario_organizacion WHERE organizacion_id=org AND estado='A') THEN CONTINUE; END IF;
        IF NOT COALESCE(exige_mfa,FALSE) THEN
            IF EXISTS(SELECT 1 FROM usuario_organizacion u JOIN cuenta_acceso c ON c.id_cuenta_acceso=u.id_usuario
               AND c.estado='A' AND c.correo_confirmado_en IS NOT NULL JOIN persona p ON p.id_persona=u.id_persona
               AND p.organizacion_id=org AND p.estado='A' JOIN persona_rol r ON r.id_persona=p.id_persona
               AND r.organizacion_id=org AND r.tipo_rol='ADMIN' AND r.vigencia_hasta IS NULL AND r.vigencia_desde<=hoy
              WHERE u.organizacion_id=org AND u.estado='A' AND u.administrar) THEN CONTINUE; END IF;
        ELSE
            IF EXISTS(SELECT 1 FROM usuario_organizacion u JOIN cuenta_acceso c ON c.id_cuenta_acceso=u.id_usuario
               JOIN factor_autenticacion f ON f.id_cuenta_acceso=c.id_cuenta_acceso AND f.estado='A'
               JOIN persona p ON p.id_persona=u.id_persona AND p.organizacion_id=org AND p.estado='A'
               JOIN persona_rol r ON r.id_persona=p.id_persona AND r.organizacion_id=org AND r.tipo_rol='ADMIN'
                 AND r.vigencia_hasta IS NULL AND r.vigencia_desde<=hoy
              WHERE u.organizacion_id=org AND u.estado='A' AND u.administrar AND c.estado='A' AND c.correo_confirmado_en IS NOT NULL
                AND NOT c.debe_cambiar_contrasena AND NOT c.debe_enrolar_mfa) THEN CONTINUE; END IF;
        END IF;
        RAISE EXCEPTION 'Una organizacion no puede quedarse sin administrador operativo (organizacion %)',org
          USING ERRCODE='integrity_constraint_violation';
    END LOOP;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER tg_organizacion_exige_estructura AFTER INSERT OR UPDATE ON organizacion
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION exigir_administrador_operativo();
CREATE CONSTRAINT TRIGGER tg_persona_exige_gobierno AFTER UPDATE ON persona
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN(OLD.estado IS DISTINCT FROM NEW.estado)
    EXECUTE FUNCTION exigir_administrador_operativo();
CREATE CONSTRAINT TRIGGER tg_rol_exige_gobierno AFTER INSERT OR UPDATE OR DELETE ON persona_rol
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION exigir_administrador_operativo();
CREATE CONSTRAINT TRIGGER tg_supervision_exige_estructura AFTER INSERT OR UPDATE OR DELETE ON supervision_agente
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION exigir_administrador_operativo();

CREATE CONSTRAINT TRIGGER tg_cuenta_exige_administrador AFTER UPDATE ON cuenta_acceso
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
 WHEN(OLD.estado IS DISTINCT FROM NEW.estado OR OLD.debe_cambiar_contrasena IS DISTINCT FROM NEW.debe_cambiar_contrasena
   OR OLD.debe_enrolar_mfa IS DISTINCT FROM NEW.debe_enrolar_mfa OR OLD.correo_confirmado_en IS DISTINCT FROM NEW.correo_confirmado_en)
 EXECUTE FUNCTION exigir_administrador_operativo();
