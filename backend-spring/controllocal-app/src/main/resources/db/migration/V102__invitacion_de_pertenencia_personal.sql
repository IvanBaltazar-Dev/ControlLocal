-- Pertenencia aceptada != credencial; no hay contraseña, secreto ni cuenta creada por gobierno.
-- RF-003 y CAT-E01 permiten comenzar con datos conocidos y acreditación progresiva.
-- Las guardas de propietario/cliente y Network se conservan en sus casos de uso.
-- Gobierno se lee sólo de UsuarioOrganizacion.administrar; consumidores comerciales migrados.
DROP INDEX uq_broker_admin_unico;
ALTER TABLE detalle_broker DROP COLUMN es_administrador;
ALTER TABLE persona ALTER COLUMN tipo_persona DROP NOT NULL;
ALTER TABLE persona ALTER COLUMN tipo_documento DROP NOT NULL;
ALTER TABLE persona ALTER COLUMN numero_documento DROP NOT NULL;
ALTER TABLE persona ALTER COLUMN nombres_o_razon_social DROP NOT NULL;

CREATE TABLE invitacion_membresia (
    id_invitacion_membresia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    referencia UUID NOT NULL UNIQUE,
    correo_cuenta VARCHAR(320) NOT NULL,
    id_persona_local BIGINT,
    nombre_local VARCHAR(150),
    tipo_persona VARCHAR(1),
    tipo_documento VARCHAR(1),
    numero_documento VARCHAR(30),
    telefono VARCHAR(20),
    correo_laboral VARCHAR(150),
    rol_principal VARCHAR(16),
    administrar BOOLEAN NOT NULL,
    id_broker_supervisor BIGINT,
    codigo_interno VARCHAR(20),
    zona VARCHAR(100),
    estado_operativo VARCHAR(1),
    creada_en TIMESTAMPTZ NOT NULL,
    vence_en TIMESTAMPTZ NOT NULL,
    id_persona_emisora BIGINT NOT NULL,
    id_rol_emisor BIGINT NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    aceptada_en TIMESTAMPTZ,
    id_cuenta_aceptante BIGINT REFERENCES cuenta_acceso(id_cuenta_acceso),
    id_membresia_aceptada BIGINT,
    id_persona_aceptada BIGINT,
    id_rol_aceptado BIGINT,
    retirada_en TIMESTAMPTZ,
    motivo_retiro VARCHAR(500),
    id_persona_retiro BIGINT,
    id_rol_retiro BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_invitacion_persona_local FOREIGN KEY(organizacion_id,id_persona_local)
        REFERENCES persona(organizacion_id,id_persona),
    CONSTRAINT fk_invitacion_emisor FOREIGN KEY(organizacion_id,id_persona_emisora)
        REFERENCES persona(organizacion_id,id_persona),
    CONSTRAINT fk_invitacion_rol_emisor FOREIGN KEY(organizacion_id,id_rol_emisor)
        REFERENCES persona_rol(organizacion_id,id_persona_rol),
    CONSTRAINT fk_invitacion_supervisor FOREIGN KEY(organizacion_id,id_broker_supervisor)
        REFERENCES persona_rol(organizacion_id,id_persona_rol),
    CONSTRAINT fk_invitacion_persona_aceptada FOREIGN KEY(organizacion_id,id_persona_aceptada)
        REFERENCES persona(organizacion_id,id_persona),
    CONSTRAINT fk_invitacion_rol_aceptado FOREIGN KEY(organizacion_id,id_rol_aceptado)
        REFERENCES persona_rol(organizacion_id,id_persona_rol),
    CONSTRAINT fk_invitacion_persona_retiro FOREIGN KEY(organizacion_id,id_persona_retiro)
        REFERENCES persona(organizacion_id,id_persona),
    CONSTRAINT fk_invitacion_rol_retiro FOREIGN KEY(organizacion_id,id_rol_retiro)
        REFERENCES persona_rol(organizacion_id,id_persona_rol),
    CONSTRAINT fk_invitacion_cuenta_miembro FOREIGN KEY(id_cuenta_aceptante,id_membresia_aceptada)
        REFERENCES usuario_organizacion(id_usuario,id_usuario_organizacion),
    CONSTRAINT ck_invitacion_rol CHECK(rol_principal IN ('AGENTE','BROKER') OR rol_principal IS NULL),
    CONSTRAINT ck_invitacion_atribucion CHECK(rol_principal IS NOT NULL OR administrar),
    CONSTRAINT ck_invitacion_supervisor CHECK((rol_principal='AGENTE' AND id_broker_supervisor IS NOT NULL)
        OR (rol_principal IS DISTINCT FROM 'AGENTE' AND id_broker_supervisor IS NULL)),
    CONSTRAINT ck_invitacion_vencimiento CHECK(vence_en>creada_en),
    CONSTRAINT ck_invitacion_correo CHECK(correo_cuenta=lower(btrim(correo_cuenta))),
    CONSTRAINT ck_invitacion_retiro CHECK(
        (retirada_en IS NULL AND motivo_retiro IS NULL AND id_persona_retiro IS NULL AND id_rol_retiro IS NULL)
        OR (retirada_en IS NOT NULL AND motivo_retiro IS NOT NULL AND id_persona_retiro IS NOT NULL
            AND id_rol_retiro IS NOT NULL AND aceptada_en IS NULL)),
    CONSTRAINT ck_invitacion_aceptacion CHECK(
        (aceptada_en IS NULL AND id_cuenta_aceptante IS NULL AND id_membresia_aceptada IS NULL
            AND id_persona_aceptada IS NULL AND id_rol_aceptado IS NULL)
        OR (aceptada_en IS NOT NULL AND id_cuenta_aceptante IS NOT NULL AND id_membresia_aceptada IS NOT NULL
            AND id_persona_aceptada IS NOT NULL AND ((rol_principal IS NULL AND id_rol_aceptado IS NULL)
                OR (rol_principal IS NOT NULL AND id_rol_aceptado IS NOT NULL))))
);
CREATE INDEX ix_invitacion_membresia_org ON invitacion_membresia(organizacion_id,id_invitacion_membresia DESC);
