CREATE TABLE documento_encargo (
 id_documento_encargo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion),
 archivo_ref uuid NOT NULL UNIQUE, id_captacion bigint REFERENCES captacion(id_captacion),
 version_encargo bigint NOT NULL, id_rol_autor bigint NOT NULL REFERENCES persona_rol(id_persona_rol),
 plantilla_version varchar(100) NOT NULL, huella varchar(64) NOT NULL,
 contenido text NOT NULL CHECK(jsonb_typeof(contenido::jsonb)='object'),
 faltantes text NOT NULL CHECK(jsonb_typeof(faltantes::jsonb)='array'),
 preparado_en timestamptz NOT NULL
);
CREATE TABLE archivo_encargo (
 id_archivo_encargo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion), archivo_ref uuid NOT NULL UNIQUE,
 id_captacion bigint REFERENCES captacion(id_captacion),
 id_documento_encargo bigint REFERENCES documento_encargo(id_documento_encargo),
 id_rol_autor bigint NOT NULL REFERENCES persona_rol(id_persona_rol),
 finalidad varchar(40) NOT NULL CHECK(finalidad IN ('PDF_ENCARGO','ACEPTACION_ENCARGO',
 'TITULARIDAD_ENCARGO','REPRESENTACION_ENCARGO','FIN_ENCARGO')),
 clave_proveedor varchar(500) NOT NULL, nombre varchar(200) NOT NULL,
 content_type varchar(100) NOT NULL, huella varchar(64) NOT NULL, registrado_en timestamptz NOT NULL
);
CREATE TABLE peticion_revision_encargo (
 id_peticion_revision_encargo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion), version bigint NOT NULL DEFAULT 0,
 id_captacion bigint NOT NULL REFERENCES captacion(id_captacion), version_presentada bigint NOT NULL,
 id_documento_encargo bigint NOT NULL REFERENCES documento_encargo(id_documento_encargo),
 id_rol_solicitante bigint NOT NULL REFERENCES persona_rol(id_persona_rol),
 estado varchar(1) NOT NULL CHECK(estado IN ('P','O','A','R')),
 evidencias text NOT NULL CHECK(jsonb_typeof(evidencias::jsonb)='array'),
 partes text NOT NULL CHECK(jsonb_typeof(partes::jsonb)='array'),
 huella_cobertura varchar(64) NOT NULL, presentada_en timestamptz NOT NULL, id_ultima_revision bigint
);
CREATE TABLE solicitud_finalizacion_encargo (
 id_solicitud_finalizacion_encargo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion), version bigint NOT NULL DEFAULT 0,
 id_captacion bigint NOT NULL REFERENCES captacion(id_captacion), version_encargo bigint NOT NULL,
 id_rol_solicitante bigint NOT NULL REFERENCES persona_rol(id_persona_rol),
 estado varchar(1) NOT NULL CHECK(estado IN ('P','O','A','R','C')),
 tipo_fin varchar(20) NOT NULL CHECK(tipo_fin IN ('FINALIZACION','RESCISION')),
 fecha_solicitada date NOT NULL, motivo text NOT NULL,
 evidencias text NOT NULL CHECK(jsonb_typeof(evidencias::jsonb)='array'),
 registrada_en timestamptz NOT NULL, id_ultima_revision bigint
);
CREATE TABLE revision_encargo (
 id_revision_encargo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion),
 id_captacion bigint NOT NULL REFERENCES captacion(id_captacion),
 id_peticion bigint REFERENCES peticion_revision_encargo(id_peticion_revision_encargo),
 id_solicitud_fin bigint REFERENCES solicitud_finalizacion_encargo(id_solicitud_finalizacion_encargo),
 version_encargo bigint NOT NULL, id_rol_actor bigint NOT NULL REFERENCES persona_rol(id_persona_rol),
 actuacion varchar(40) NOT NULL, observaciones text,
 snapshot text NOT NULL CHECK(jsonb_typeof(snapshot::jsonb)='object'),
 huella_cobertura varchar(64) NOT NULL, registrada_en timestamptz NOT NULL,
 CHECK(NOT(id_peticion IS NOT NULL AND id_solicitud_fin IS NOT NULL))
);
CREATE TABLE composicion_encargo (
 id_composicion_encargo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion),
 id_captacion bigint NOT NULL REFERENCES captacion(id_captacion), version_contenido bigint NOT NULL,
 unidades text NOT NULL CHECK(jsonb_typeof(unidades::jsonb)='array'), total_declarado numeric(18,4),
 moneda varchar(3), procedencia text NOT NULL, registrada_en timestamptz NOT NULL,
 id_rol_actor bigint NOT NULL REFERENCES persona_rol(id_persona_rol),
 CHECK((total_declarado IS NULL AND moneda IS NULL) OR (total_declarado>=0 AND moneda IS NOT NULL))
);
