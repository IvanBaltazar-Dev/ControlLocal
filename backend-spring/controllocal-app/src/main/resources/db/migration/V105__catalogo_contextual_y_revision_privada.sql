CREATE TABLE perfil_catalogo_opciones (
    id_perfil BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    id_catalogo_atributo BIGINT NOT NULL REFERENCES catalogo_atributo(id_catalogo_atributo),
    jurisdiccion VARCHAR(160) NOT NULL CHECK(length(trim(jurisdiccion))>0),
    version_fuente VARCHAR(100) NOT NULL CHECK(length(trim(version_fuente))>0),
    fuente_definicion TEXT NOT NULL CHECK(length(trim(fuente_definicion))>0),
    version_definicion BIGINT NOT NULL DEFAULT 0 CHECK(version_definicion>=0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_retiro TIMESTAMPTZ,
    CONSTRAINT ck_perfil_catalogo_retiro CHECK(activo=(fecha_retiro IS NULL))
);
CREATE UNIQUE INDEX uq_perfil_catalogo_actual
    ON perfil_catalogo_opciones(organizacion_id,id_catalogo_atributo,jurisdiccion) WHERE activo;

-- Reutiliza OpcionDeAtributo como valor embebido: no otro vocabulario/motor.
CREATE TABLE perfil_catalogo_opcion (
    id_perfil BIGINT NOT NULL REFERENCES perfil_catalogo_opciones(id_perfil),
    valor VARCHAR(40) NOT NULL,
    rotulo VARCHAR(120) NOT NULL,
    orden INTEGER NOT NULL DEFAULT 100,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY(id_perfil,valor)
);

CREATE FUNCTION exigir_base_de_perfil_catalogo() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE base catalogo_atributo%ROWTYPE;
BEGIN
    SELECT * INTO base FROM catalogo_atributo WHERE id_catalogo_atributo=NEW.id_catalogo_atributo;
    IF NOT FOUND OR (base.organizacion_id IS NOT NULL AND base.organizacion_id<>NEW.organizacion_id)
       OR NOT (base.tipo_dato IN ('LISTA','LISTA_MULTIPLE')
          OR (base.clave='zonificacion' AND base.sujeto='PROPIEDAD' AND base.tipo_dato='TEXTO')) THEN
        RAISE EXCEPTION 'El perfil requiere una lista común/propia o zonificación física de almacenamiento TEXTO'
          USING ERRCODE='check_violation';
    END IF;
    IF TG_OP='UPDATE' AND (OLD.organizacion_id IS DISTINCT FROM NEW.organizacion_id
       OR OLD.id_catalogo_atributo IS DISTINCT FROM NEW.id_catalogo_atributo
       OR OLD.jurisdiccion IS DISTINCT FROM NEW.jurisdiccion) THEN
        RAISE EXCEPTION 'Un perfil no cambia tenant, definición base ni jurisdicción'
          USING ERRCODE='check_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tg_perfil_catalogo_base BEFORE INSERT OR UPDATE ON perfil_catalogo_opciones
    FOR EACH ROW EXECUTE FUNCTION exigir_base_de_perfil_catalogo();

-- El snapshot es el estado ANTERIOR hallado al versionar/retirar, no una
-- atribución retrospectiva de quién creó los datos que ya existían.
CREATE TABLE revision_catalogo_gobernado (
    id_revision BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    clase_recurso VARCHAR(20) NOT NULL CHECK(clase_recurso IN ('DEFINICION_PRIVADA','PERFIL_OPCIONES')),
    id_recurso BIGINT NOT NULL,
    version_definicion BIGINT NOT NULL CHECK(version_definicion>=0),
    snapshot_json TEXT NOT NULL CHECK(jsonb_typeof(snapshot_json::jsonb)='object'),
    actuacion VARCHAR(20) NOT NULL CHECK(actuacion IN ('VERSIONAR','RETIRAR')),
    id_rol_actor BIGINT NOT NULL,
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_revision_catalogo_actor FOREIGN KEY(organizacion_id,id_rol_actor)
        REFERENCES persona_rol(organizacion_id,id_persona_rol),
    CONSTRAINT uq_revision_catalogo_version UNIQUE(organizacion_id,clase_recurso,id_recurso,version_definicion)
);
CREATE FUNCTION proteger_revision_catalogo() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'La revisión de catálogo conserva su snapshot y no admite UPDATE/DELETE'
      USING ERRCODE='restrict_violation';
END $$;
CREATE TRIGGER tg_revision_catalogo_append_only BEFORE UPDATE OR DELETE ON revision_catalogo_gobernado
    FOR EACH ROW EXECUTE FUNCTION proteger_revision_catalogo();
