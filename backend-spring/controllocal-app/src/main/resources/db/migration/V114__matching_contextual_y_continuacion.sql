-- D4-29–40/C3: continuación técnica privada. No almacena fichas, condiciones ni resultados ajenos.
-- La referencia opaca no concede permiso: Core revalida actor/contexto/origen y cada entrega.
CREATE TABLE matching_recorrido (
    id_recorrido UUID PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    id_persona BIGINT NOT NULL,
    id_rol BIGINT NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('AGENTE','BROKER')),
    huella_contexto VARCHAR(64) NOT NULL CHECK (huella_contexto ~ '^[a-f0-9]{64}$'),
    tipo_origen VARCHAR(20) NOT NULL CHECK (tipo_origen IN ('DEMANDA','ENCARGO','PROSPECCION','FISICO','CAPTURA')),
    id_origen BIGINT NOT NULL CHECK (id_origen > 0),
    version_origen BIGINT NOT NULL CHECK (version_origen >= 0),
    huella_criterios VARCHAR(64) NOT NULL CHECK (huella_criterios ~ '^[a-f0-9]{64}$'),
    modalidad VARCHAR(12) NOT NULL CHECK (modalidad IN ('COMERCIAL','PRELIMINAR')),
    capas VARCHAR(20) NOT NULL CHECK (string_to_array(capas, ',') <@ ARRAY['L0','L1','L2']::text[] AND capas <> ''),
    capas_no_disponibles VARCHAR(20) NOT NULL DEFAULT '' CHECK (capas_no_disponibles = '' OR
        string_to_array(capas_no_disponibles, ',') <@ string_to_array(capas, ',')),
    categoria VARCHAR(32) NOT NULL CHECK (categoria IN ('COMERCIAL_CONFIRMADA','OBLIGATORIAS_PENDIENTES',
        'HABILITACION_PENDIENTE','NO_HABILITADA','INCOMPATIBLE','POTENCIAL')),
    version_regla VARCHAR(80) NOT NULL CHECK (btrim(version_regla) <> ''),
    corte TIMESTAMPTZ NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL,
    vence_en TIMESTAMPTZ NOT NULL,
    tamano INTEGER NOT NULL CHECK (tamano BETWEEN 1 AND 50),
    CONSTRAINT uq_matching_recorrido_org UNIQUE (organizacion_id,id_recorrido),
    CONSTRAINT fk_matching_persona FOREIGN KEY (organizacion_id,id_persona)
        REFERENCES persona(organizacion_id,id_persona),
    CONSTRAINT fk_matching_rol FOREIGN KEY (organizacion_id,id_rol)
        REFERENCES persona_rol(organizacion_id,id_persona_rol),
    CONSTRAINT ck_matching_continuacion CHECK (vence_en = creado_en + interval '15 minutes'),
    CONSTRAINT ck_matching_l2_solo_demanda CHECK (tipo_origen = 'DEMANDA' OR NOT ('L2'=ANY(string_to_array(capas,','))))
);

-- La identidad contextual no puede combinar Persona y rol de dos miembros distintos.
CREATE FUNCTION exigir_identidad_matching() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM persona_rol r WHERE r.organizacion_id=NEW.organizacion_id
        AND r.id_persona_rol=NEW.id_rol AND r.id_persona=NEW.id_persona AND r.tipo_rol=NEW.rol) THEN
        RAISE EXCEPTION 'El recorrido conserva la identidad contextual exacta de Persona/rol/organización' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tg_matching_identidad BEFORE INSERT ON matching_recorrido
    FOR EACH ROW EXECUTE FUNCTION exigir_identidad_matching();

CREATE TABLE matching_referencia (
    id_referencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    id_recorrido UUID NOT NULL,
    ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
    capa VARCHAR(2) NOT NULL CHECK(capa IN ('L0','L1','L2')),
    tipo_recurso VARCHAR(20) NOT NULL CHECK (tipo_recurso IN ('ENCARGO','NETWORK','INTERNA','PROSPECCION','FISICO','CAPTURA')),
    referencia_recurso VARCHAR(160) NOT NULL CHECK (btrim(referencia_recurso) <> ''),
    version_recurso BIGINT NOT NULL CHECK (version_recurso >= 0),
    huella_proyeccion VARCHAR(64) NOT NULL CHECK (huella_proyeccion ~ '^[a-f0-9]{64}$'),
    id_demanda BIGINT NOT NULL CHECK (id_demanda > 0),
    version_demanda BIGINT NOT NULL CHECK (version_demanda >= 0),
    huella_criterios VARCHAR(64) NOT NULL CHECK (huella_criterios ~ '^[a-f0-9]{64}$'),
    CONSTRAINT fk_matching_referencia_recorrido FOREIGN KEY (organizacion_id,id_recorrido)
        REFERENCES matching_recorrido(organizacion_id,id_recorrido) ON DELETE CASCADE,
    CONSTRAINT fk_matching_referencia_demanda FOREIGN KEY(organizacion_id,id_demanda)
        REFERENCES requerimiento_cliente(organizacion_id,id_requerimiento),
    CONSTRAINT ck_matching_referencia_capa CHECK((capa='L2')=(tipo_recurso='NETWORK')
        AND(tipo_recurso<>'INTERNA' OR capa='L1')),
    CONSTRAINT uq_matching_ordinal UNIQUE (organizacion_id,id_recorrido,ordinal),
    CONSTRAINT uq_matching_candidato UNIQUE (organizacion_id,id_recorrido,id_demanda,tipo_recurso,referencia_recurso)
);

CREATE TABLE matching_cursor (
    referencia VARCHAR(43) PRIMARY KEY CHECK (referencia ~ '^[A-Za-z0-9_-]{43}$'),
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    id_recorrido UUID NOT NULL,
    posicion INTEGER NOT NULL CHECK (posicion >= 0),
    CONSTRAINT fk_matching_cursor_recorrido FOREIGN KEY (organizacion_id,id_recorrido)
        REFERENCES matching_recorrido(organizacion_id,id_recorrido) ON DELETE CASCADE,
    CONSTRAINT uq_matching_posicion UNIQUE (organizacion_id,id_recorrido,posicion)
);

CREATE INDEX ix_matching_recorrido_vencimiento ON matching_recorrido(organizacion_id,vence_en);

-- El corte, orden y vínculo de contexto son originales: no se reescriben al navegar/renovar.
-- DELETE sigue disponible para retirar exclusivamente metadata técnica vencida.
CREATE FUNCTION impedir_reescritura_matching() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'La metadata original de matching no se reescribe' USING ERRCODE='23514';
END;
$$;
CREATE TRIGGER tg_matching_recorrido_original BEFORE UPDATE ON matching_recorrido
    FOR EACH ROW EXECUTE FUNCTION impedir_reescritura_matching();
CREATE TRIGGER tg_matching_referencia_original BEFORE UPDATE ON matching_referencia
    FOR EACH ROW EXECUTE FUNCTION impedir_reescritura_matching();
CREATE TRIGGER tg_matching_cursor_original BEFORE UPDATE ON matching_cursor
    FOR EACH ROW EXECUTE FUNCTION impedir_reescritura_matching();

COMMENT ON TABLE matching_recorrido IS 'Corte/alcance de consulta privada D4; no permiso ni estado comercial.';
COMMENT ON TABLE matching_referencia IS 'Sólo referencias/versiones/capa/ordinal/grupo de cartera autorizada o proyección L1/L2 admitida; sin atributos ajenos.';
COMMENT ON TABLE matching_cursor IS 'Continuación opaca, ligada al mismo actor/contexto/corte; no extiende los quince minutos.';
