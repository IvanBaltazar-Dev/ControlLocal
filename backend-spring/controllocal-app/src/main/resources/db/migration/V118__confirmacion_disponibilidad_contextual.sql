-- CAT-R21/E28/D2: hecho específico, evidencia/procedencia e historia conservada.
-- No crea tareas, no cambia disponibilidad física ni estado/vigencia contractual, no concede Network.
CREATE TABLE confirmacion_disponibilidad_contextual (
    id_confirmacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    tipo_recurso VARCHAR(10) NOT NULL CHECK (tipo_recurso IN ('ENCARGO','DEMANDA')),
    id_recurso BIGINT NOT NULL CHECK (id_recurso > 0),
    operacion VARCHAR(10) NOT NULL CHECK (operacion IN ('VENTA','ALQUILER')),
    aspecto VARCHAR(40) NOT NULL CHECK (aspecto='DISPONIBILIDAD_COMERCIAL'),
    contexto VARCHAR(100) NOT NULL CHECK (btrim(contexto)<>''),
    version_registro BIGINT NOT NULL CHECK (version_registro>0),
    version_recurso_observada BIGINT NOT NULL CHECK (version_recurso_observada>=0),
    disponible BOOLEAN NOT NULL,
    precision_hecho VARCHAR(8) NOT NULL CHECK (precision_hecho IN ('INSTANTE','FECHA')),
    fecha_hecho TIMESTAMPTZ,
    fecha_sin_hora DATE,
    base_frescura TIMESTAMPTZ NOT NULL,
    registrado_en TIMESTAMPTZ NOT NULL,
    id_persona_confirmante BIGINT NOT NULL,
    id_rol_confirmante BIGINT NOT NULL,
    fuente TEXT NOT NULL CHECK (btrim(fuente)<>''),
    evidencia_ref TEXT NOT NULL CHECK (btrim(evidencia_ref)<>''),
    procedencia TEXT NOT NULL CHECK (jsonb_typeof(procedencia::jsonb)='object'),
    huella_sesion VARCHAR(64) NOT NULL CHECK (huella_sesion ~ '^[a-f0-9]{64}$'),
    referencia_sesion_hash VARCHAR(64) NOT NULL CHECK (referencia_sesion_hash ~ '^[a-f0-9]{64}$'),
    revision_contexto BIGINT NOT NULL CHECK (revision_contexto>=0),
    CONSTRAINT uq_disponibilidad_contexto_version UNIQUE
        (organizacion_id,tipo_recurso,id_recurso,operacion,aspecto,contexto,version_registro),
    CONSTRAINT fk_disponibilidad_persona FOREIGN KEY (organizacion_id,id_persona_confirmante)
        REFERENCES persona(organizacion_id,id_persona),
    CONSTRAINT fk_disponibilidad_rol FOREIGN KEY (organizacion_id,id_rol_confirmante)
        REFERENCES persona_rol(organizacion_id,id_persona_rol),
    CONSTRAINT ck_disponibilidad_precision CHECK (
        (precision_hecho='INSTANTE' AND fecha_hecho IS NOT NULL AND fecha_sin_hora IS NULL
            AND base_frescura=fecha_hecho AND fecha_hecho<=registrado_en)
        OR (precision_hecho='FECHA' AND fecha_hecho IS NULL AND fecha_sin_hora IS NOT NULL
            AND base_frescura=(fecha_sin_hora::timestamp AT TIME ZONE 'America/Lima')
            AND fecha_sin_hora<=(registrado_en AT TIME ZONE 'America/Lima')::date))
);

CREATE FUNCTION validar_confirmacion_disponibilidad_contextual() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    responsable BIGINT;
    version_actual BIGINT;
    codigo_operacion VARCHAR(1);
    contexto_actual TEXT;
BEGIN
    IF TG_OP<>'INSERT' THEN
        RAISE EXCEPTION 'La confirmación original y sus antecedentes se conservan' USING ERRCODE='23514';
    END IF;
    IF NEW.tipo_recurso='ENCARGO' THEN
        SELECT c.id_rol_agente,c.version,c.motivo_operacion,
            CASE WHEN c.id_composicion_actual IS NULL THEN 'UNIDAD:'||c.id_propiedad
                 ELSE 'COMPOSICION:'||c.id_composicion_actual END
          INTO responsable,version_actual,codigo_operacion,contexto_actual
          FROM captacion c WHERE c.organizacion_id=NEW.organizacion_id AND c.id_captacion=NEW.id_recurso
          FOR SHARE;
    ELSE
        SELECT r.id_rol_responsable,r.version,r.operacion,'DEMANDA:'||r.id_requerimiento
          INTO responsable,version_actual,codigo_operacion,contexto_actual
          FROM requerimiento_cliente r WHERE r.organizacion_id=NEW.organizacion_id AND r.id_requerimiento=NEW.id_recurso
          FOR SHARE;
    END IF;
    IF NOT FOUND THEN RAISE EXCEPTION 'Recurso inexistente en esta organización' USING ERRCODE='23503'; END IF;
    IF version_actual IS DISTINCT FROM NEW.version_recurso_observada THEN
        RAISE EXCEPTION 'Cambió el recurso observado' USING ERRCODE='40001';
    END IF;
    IF responsable IS NULL OR responsable IS DISTINCT FROM NEW.id_rol_confirmante OR contexto_actual IS DISTINCT FROM NEW.contexto
        OR codigo_operacion IS DISTINCT FROM (CASE NEW.operacion WHEN 'VENTA' THEN 'V' ELSE 'A' END) THEN
        RAISE EXCEPTION 'La confirmación no corresponde al responsable/operación/contexto actual' USING ERRCODE='23514';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM persona_rol p WHERE p.organizacion_id=NEW.organizacion_id
        AND p.id_persona_rol=NEW.id_rol_confirmante AND p.id_persona=NEW.id_persona_confirmante AND p.tipo_rol='AGENTE') THEN
        RAISE EXCEPTION 'Sólo el agente responsable confirma este contexto' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_disponibilidad_contextual_guardas BEFORE INSERT OR UPDATE OR DELETE
    ON confirmacion_disponibilidad_contextual FOR EACH ROW
    EXECUTE FUNCTION validar_confirmacion_disponibilidad_contextual();

COMMENT ON TABLE confirmacion_disponibilidad_contextual IS
    'D2: confirmación independiente por recurso/operación/aspecto/contexto. Reasignar no cambia la clave ni reinicia relojes.';
COMMENT ON COLUMN confirmacion_disponibilidad_contextual.base_frescura IS
    'Instante explícito o inicio conservador del día Lima si precisión FECHA; no representa una hora declarada para esa fecha.';

CREATE FUNCTION impedir_truncate_disponibilidad_contextual() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Los hechos originales de disponibilidad no se eliminan por TRUNCATE' USING ERRCODE='23514';
END $$;
CREATE TRIGGER tg_disponibilidad_contextual_no_truncate BEFORE TRUNCATE
    ON confirmacion_disponibilidad_contextual FOR EACH STATEMENT
    EXECUTE FUNCTION impedir_truncate_disponibilidad_contextual();
