CREATE FUNCTION conservar_identidad_seguimiento_c4() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' AND ROW(NEW.id_seguimiento,NEW.organizacion_id,NEW.id_prospeccion,NEW.destinatario_clave,NEW.finalidad,NEW.registrado_en,NEW.id_antecedente)
 IS DISTINCT FROM ROW(OLD.id_seguimiento,OLD.organizacion_id,OLD.id_prospeccion,OLD.destinatario_clave,OLD.finalidad,OLD.registrado_en,OLD.id_antecedente) THEN
  RAISE EXCEPTION 'La revisión conserva recurso, destinatario, finalidad e inicio originales' USING ERRCODE='23514';
 END IF;
 IF NEW.id_antecedente IS NOT NULL AND NOT EXISTS(
   SELECT 1 FROM seguimiento_prospeccion a WHERE a.organizacion_id=NEW.organizacion_id AND a.id_seguimiento=NEW.id_antecedente
     AND a.id_prospeccion=NEW.id_prospeccion AND a.destinatario_clave=NEW.destinatario_clave AND a.finalidad=NEW.finalidad) THEN
   RAISE EXCEPTION 'El antecedente conserva el contexto y destinatario de la revisión' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER conservar_identidad_seguimiento BEFORE INSERT OR UPDATE ON seguimiento_prospeccion FOR EACH ROW EXECUTE FUNCTION conservar_identidad_seguimiento_c4();

