CREATE TABLE expediente_operacion (
 id_expediente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 secuencia_actividad BIGINT NOT NULL DEFAULT 0 CHECK(secuencia_actividad>=0),
 id_captacion BIGINT NOT NULL, id_oportunidad BIGINT NOT NULL,
 id_revision_pacto BIGINT NOT NULL, id_solicitud_alquiler BIGINT,id_contrato_origen BIGINT,
 id_acuerdo_c4 BIGINT,version_acuerdo_c4 BIGINT,
 id_contrato_alquiler BIGINT, id_contrato_venta BIGINT,
 id_revision_presentada BIGINT,id_revision_aplicable BIGINT,id_revision_fuente BIGINT,id_revision_evaluada BIGINT,
 registrado_en TIMESTAMPTZ NOT NULL,
 UNIQUE(organizacion_id,id_expediente),
 UNIQUE(organizacion_id,id_expediente,id_captacion),
 CHECK((id_acuerdo_c4 IS NULL)=(version_acuerdo_c4 IS NULL)),
 FOREIGN KEY(organizacion_id,id_oportunidad,id_captacion) REFERENCES oportunidad_comercial(organizacion_id,id_oportunidad,id_captacion),
 FOREIGN KEY(organizacion_id,id_captacion,id_revision_pacto) REFERENCES revision_encargo(organizacion_id,id_captacion,id_revision_encargo),
 FOREIGN KEY(organizacion_id,id_acuerdo_c4,version_acuerdo_c4) REFERENCES acuerdo_aceptado(organizacion_id,id_acuerdo,version),
 FOREIGN KEY(organizacion_id,id_oportunidad,id_solicitud_alquiler) REFERENCES solicitud_alquiler(organizacion_id,id_oportunidad,id_solicitud),
 FOREIGN KEY(organizacion_id,id_oportunidad,id_contrato_alquiler) REFERENCES contrato_alquiler(organizacion_id,id_oportunidad,id_contrato_alquiler),
 FOREIGN KEY(organizacion_id,id_oportunidad,id_contrato_origen) REFERENCES contrato_alquiler(organizacion_id,id_oportunidad,id_contrato_alquiler),
 FOREIGN KEY(organizacion_id,id_oportunidad,id_contrato_venta) REFERENCES contrato_compraventa(organizacion_id,id_oportunidad,id_contrato_compraventa)
);
CREATE UNIQUE INDEX uq_expediente_original ON expediente_operacion(organizacion_id,id_oportunidad) WHERE id_contrato_origen IS NULL;
CREATE UNIQUE INDEX uq_expediente_renovacion ON expediente_operacion(organizacion_id,id_contrato_origen) WHERE id_contrato_origen IS NOT NULL;
CREATE TABLE revision_expediente_operacion (
 id_revision_expediente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id BIGINT NOT NULL,id_expediente BIGINT NOT NULL,
 version_revisada BIGINT NOT NULL CHECK(version_revisada>=0),
 tipo_registro VARCHAR(20) NOT NULL CHECK(tipo_registro IN ('PRESENTACION','REVISION')),
 decision VARCHAR(20) CHECK(decision IN ('APROBAR','OBSERVAR','RECHAZAR')),
 id_presentacion BIGINT,antecedente BIGINT,id_rol_actor BIGINT NOT NULL,
 contenido_json TEXT NOT NULL CHECK(jsonb_typeof(contenido_json::jsonb)='object'),
 registrado_en TIMESTAMPTZ NOT NULL,
 CHECK((tipo_registro='PRESENTACION' AND decision IS NULL) OR (tipo_registro='REVISION' AND decision IS NOT NULL AND id_presentacion IS NOT NULL)),
 UNIQUE(organizacion_id,id_expediente,id_revision_expediente),
 FOREIGN KEY(organizacion_id,id_expediente) REFERENCES expediente_operacion(organizacion_id,id_expediente),
 FOREIGN KEY(organizacion_id,id_expediente,id_presentacion) REFERENCES revision_expediente_operacion(organizacion_id,id_expediente,id_revision_expediente),
 FOREIGN KEY(organizacion_id,id_expediente,antecedente) REFERENCES revision_expediente_operacion(organizacion_id,id_expediente,id_revision_expediente)
);
CREATE TABLE hito_contractual (
 id_hito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id BIGINT NOT NULL,id_expediente BIGINT NOT NULL,
 version BIGINT NOT NULL DEFAULT 0 CHECK(version>=0),
 tipo VARCHAR(30) NOT NULL CHECK(tipo IN ('MINUTA','ESCRITURA','CONTRATO_ALQUILER')),
 id_revision_informada BIGINT,id_revision_confirmada BIGINT,
 UNIQUE(organizacion_id,id_hito),UNIQUE(organizacion_id,id_expediente,id_hito),
 UNIQUE(organizacion_id,id_expediente,tipo),
 FOREIGN KEY(organizacion_id,id_expediente) REFERENCES expediente_operacion(organizacion_id,id_expediente)
);
CREATE TABLE revision_hito_contractual (
 id_revision_hito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id BIGINT NOT NULL,id_expediente BIGINT NOT NULL,id_hito BIGINT NOT NULL,
 tipo_registro VARCHAR(20) NOT NULL CHECK(tipo_registro IN ('INFORMACION','CONFIRMACION','RECTIFICACION')),
 fecha_efectiva DATE,id_revision_expediente BIGINT,antecedente BIGINT,id_rol_actor BIGINT NOT NULL,
 contenido_json TEXT NOT NULL CHECK(jsonb_typeof(contenido_json::jsonb)='object'),registrado_en TIMESTAMPTZ NOT NULL,
 CHECK(tipo_registro='INFORMACION' OR (fecha_efectiva IS NOT NULL AND id_revision_expediente IS NOT NULL)),
 UNIQUE(organizacion_id,id_hito,id_revision_hito),
 UNIQUE(organizacion_id,id_expediente,id_hito,id_revision_hito),
 FOREIGN KEY(organizacion_id,id_expediente,id_hito) REFERENCES hito_contractual(organizacion_id,id_expediente,id_hito),
 FOREIGN KEY(organizacion_id,id_expediente,id_revision_expediente) REFERENCES revision_expediente_operacion(organizacion_id,id_expediente,id_revision_expediente),
 FOREIGN KEY(organizacion_id,id_expediente,id_hito,antecedente) REFERENCES revision_hito_contractual(organizacion_id,id_expediente,id_hito,id_revision_hito)
);
