-- La rectificación no reescribe una decisión de reparto anterior. Su suma pertenece
-- a la evaluación inmutable que la sustentó, nunca al cálculo actual de la cabecera.
CREATE FUNCTION validar_base_reparto_comision_c5() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE base numeric;
BEGIN
 IF NEW.id_contexto_economico IS NULL THEN RETURN NEW; END IF;
 IF NEW.parte_agente IS NULL AND NEW.parte_empresa IS NULL AND NEW.id_evaluacion_base_reparto IS NULL THEN
  RETURN NEW;
 END IF;
 IF NEW.parte_agente IS NULL OR NEW.parte_empresa IS NULL OR NEW.id_evaluacion_base_reparto IS NULL THEN
  RAISE EXCEPTION 'El reparto requiere ambas partes y su evaluación acreditada' USING ERRCODE='23514';
 END IF;
 SELECT (resultado::jsonb#>>'{calculo,cuantia,importe}')::numeric INTO base
 FROM comision_evaluacion WHERE organizacion_id=NEW.organizacion_id
  AND id_comision_liquidacion=NEW.id_comision_liquidacion
  AND id_contexto_economico=NEW.id_contexto_economico
  AND id_comision_evaluacion=NEW.id_evaluacion_base_reparto;
 IF base IS NULL OR NEW.parte_agente+NEW.parte_empresa<>base THEN
  RAISE EXCEPTION 'El reparto no conserva su base histórica' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER base_reparto_comision_c5 BEFORE INSERT OR UPDATE ON comision_liquidacion
 FOR EACH ROW EXECUTE FUNCTION validar_base_reparto_comision_c5();

-- La fuente C4 debe pertenecer al mismo episodio; REVISION_C5 conserva la revisión exacta.
CREATE FUNCTION validar_fuente_comision_c5() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.tipo_fuente='REVISION_C5' THEN
  IF NEW.id_fuente<>NEW.id_contexto_economico OR NOT EXISTS(
   SELECT 1 FROM revision_expediente_operacion r WHERE r.organizacion_id=NEW.organizacion_id
    AND r.id_expediente=NEW.id_contexto_economico AND r.id_revision_expediente=NEW.revision_fuente) THEN
    RAISE EXCEPTION 'La fuente económica no pertenece al contexto' USING ERRCODE='23503';
  END IF;
 ELSIF NEW.tipo_fuente='ACUERDO_C4' AND NOT EXISTS(
  SELECT 1 FROM acuerdo_aceptado a JOIN oferta o ON o.organizacion_id=a.organizacion_id AND o.id_oferta=a.id_oferta
   JOIN expediente_operacion e ON e.organizacion_id=o.organizacion_id AND e.id_oportunidad=o.id_oportunidad
   WHERE a.organizacion_id=NEW.organizacion_id AND a.id_acuerdo=NEW.id_fuente AND a.version=NEW.revision_fuente
    AND e.id_expediente=NEW.id_contexto_economico) THEN
   RAISE EXCEPTION 'El acuerdo económico no pertenece al contexto' USING ERRCODE='23503';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER fuente_comision_c5 BEFORE INSERT ON comision_evaluacion FOR EACH ROW EXECUTE FUNCTION validar_fuente_comision_c5();

-- Una raíz C5 no admite nuevos movimientos por la frontera sin metadatos de filas anteriores.
CREATE FUNCTION validar_movimiento_comision_c5() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM comision_liquidacion c WHERE c.organizacion_id=NEW.organizacion_id
  AND c.id_comision_liquidacion=NEW.id_comision_liquidacion AND c.id_contexto_economico IS NOT NULL) THEN
  IF NEW.id_comision_evaluacion IS NULL OR NEW.id_revision_pacto IS NULL OR NEW.id_persona_rol_actor IS NULL
    OR NEW.procedencia IS NULL OR NEW.clave_idempotencia IS NULL OR NEW.huella_comando IS NULL THEN
   RAISE EXCEPTION 'El movimiento debe conservar su actuación y evaluación exactas' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER movimiento_comision_c5 BEFORE INSERT ON comision_movimiento FOR EACH ROW EXECUTE FUNCTION validar_movimiento_comision_c5();

