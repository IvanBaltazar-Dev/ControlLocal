-- RF080: versiones de contenido inmutables. Los dos binarios tienen finalidades distintas.
CREATE TABLE pieza_comercial (
 id_pieza bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL,
 referencia uuid NOT NULL UNIQUE,familia uuid NOT NULL,version_contenido bigint NOT NULL CHECK(version_contenido>0),
 id_captacion bigint NOT NULL,id_propiedad bigint NOT NULL,id_rol_responsable bigint NOT NULL,
 solicitud text NOT NULL CHECK(jsonb_typeof(solicitud::jsonb)='object'),
 proyeccion text NOT NULL CHECK(jsonb_typeof(proyeccion::jsonb)='object'),
 huella_origen varchar(64) NOT NULL CHECK(huella_origen ~ '^[0-9a-f]{64}$'),
 formato varchar(30) NOT NULL CHECK(formato IN('PDF_A4','PNG_VERTICAL')),
 plantilla_version varchar(60) NOT NULL,preparada_en timestamptz NOT NULL,
 revision_fila bigint NOT NULL DEFAULT 0,
 archivo_privado_ref uuid UNIQUE,clave_privada text,huella_privada varchar(64),
 archivo_difusion_ref uuid UNIQUE,clave_difusion text,huella_difusion varchar(64),autorizada_en timestamptz,
 UNIQUE(organizacion_id,id_pieza),UNIQUE(organizacion_id,familia,version_contenido),
 FOREIGN KEY(organizacion_id,id_captacion) REFERENCES captacion(organizacion_id,id_captacion),
 FOREIGN KEY(organizacion_id,id_propiedad) REFERENCES propiedad(organizacion_id,id_propiedad),
 FOREIGN KEY(organizacion_id,id_rol_responsable) REFERENCES persona_rol(organizacion_id,id_persona_rol),
 CHECK(num_nonnulls(archivo_privado_ref,clave_privada,huella_privada) IN(0,3)),
 CHECK(num_nonnulls(archivo_difusion_ref,clave_difusion,huella_difusion,autorizada_en) IN(0,4)),
 CHECK(huella_privada IS NULL OR huella_privada ~ '^[0-9a-f]{64}$'),
 CHECK(huella_difusion IS NULL OR huella_difusion ~ '^[0-9a-f]{64}$')
);
-- Una ficha puede describir la primaria o una unidad del objeto compuesto vigente.
-- La relación física RF014 por sí sola no satisface esta condición comercial.
CREATE FUNCTION verificar_objeto_pieza_c6() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(
  SELECT 1 FROM captacion c WHERE c.organizacion_id=NEW.organizacion_id AND c.id_captacion=NEW.id_captacion
   AND(c.id_propiedad=NEW.id_propiedad OR EXISTS(
    SELECT 1 FROM composicion_encargo o CROSS JOIN LATERAL jsonb_array_elements(o.unidades::jsonb) u
    WHERE o.organizacion_id=c.organizacion_id AND o.id_captacion=c.id_captacion
      AND o.id_composicion_encargo=c.id_composicion_actual AND (u->>'idPropiedad')::bigint=NEW.id_propiedad
   ))
 ) THEN RAISE EXCEPTION 'La unidad de la ficha no pertenece al objeto comercial del Encargo'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER pieza_c6_objeto_comercial BEFORE INSERT ON pieza_comercial
 FOR EACH ROW EXECUTE FUNCTION verificar_objeto_pieza_c6();
CREATE FUNCTION conservar_version_pieza_c6() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Las versiones de pieza conservan su historia'; END IF;
 IF ROW(NEW.organizacion_id,NEW.referencia,NEW.familia,NEW.version_contenido,NEW.id_captacion,
   NEW.id_propiedad,NEW.id_rol_responsable,NEW.solicitud,NEW.proyeccion,NEW.huella_origen,NEW.formato,NEW.plantilla_version,NEW.preparada_en)
  IS DISTINCT FROM ROW(OLD.organizacion_id,OLD.referencia,OLD.familia,OLD.version_contenido,OLD.id_captacion,
   OLD.id_propiedad,OLD.id_rol_responsable,OLD.solicitud,OLD.proyeccion,OLD.huella_origen,OLD.formato,OLD.plantilla_version,OLD.preparada_en)
  THEN RAISE EXCEPTION 'El contenido de la pieza es versionado; regenere sin sobrescribir'; END IF;
 IF OLD.archivo_privado_ref IS NOT NULL AND
  ROW(NEW.archivo_privado_ref,NEW.clave_privada,NEW.huella_privada) IS DISTINCT FROM
  ROW(OLD.archivo_privado_ref,OLD.clave_privada,OLD.huella_privada)
  THEN RAISE EXCEPTION 'La salida privada conserva su binario e integridad'; END IF;
 IF OLD.archivo_difusion_ref IS NOT NULL AND
  ROW(NEW.archivo_difusion_ref,NEW.clave_difusion,NEW.huella_difusion,NEW.autorizada_en) IS DISTINCT FROM
  ROW(OLD.archivo_difusion_ref,OLD.clave_difusion,OLD.huella_difusion,OLD.autorizada_en)
  THEN RAISE EXCEPTION 'La salida autorizada conserva su binario e integridad'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER pieza_c6_conservar_version BEFORE UPDATE OR DELETE ON pieza_comercial
 FOR EACH ROW EXECUTE FUNCTION conservar_version_pieza_c6();
