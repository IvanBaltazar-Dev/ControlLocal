-- RF080: diario técnico recuperable, separado de derechos/consumo y de las autorizaciones del recurso.
CREATE TABLE intento_salida_binaria (
 id_intento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion),
 operacion uuid NOT NULL,
 numero integer NOT NULL CHECK(numero>0),
 fuente varchar(2000) NOT NULL CHECK(length(btrim(fuente))>0),
 clave_proveedor text NOT NULL UNIQUE,
 extension varchar(12) NOT NULL,
 content_type varchar(100) NOT NULL,
 huella varchar(64) NOT NULL CHECK(huella ~ '^[0-9a-f]{64}$'),
 bytes bigint NOT NULL CHECK(bytes>=0),
 estado varchar(40) NOT NULL CHECK(estado IN('PREPARADO','ESCRITO_VERIFICADO','INCIERTO','VINCULADO','PENDIENTE_RETIRO','RETIRADO_VERIFICADO')),
 escritura_incierta boolean NOT NULL DEFAULT true,
 registrado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 actualizado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 ultima_verificacion_en timestamptz,
 resultado_tecnico varchar(80),
 UNIQUE(organizacion_id,operacion,numero),
 CHECK(clave_proveedor LIKE 'tenant/'||organizacion_id::text||'/salidas/'||operacion::text||'/%')
);
CREATE INDEX ix_intentos_binarios_recuperables ON intento_salida_binaria(id_intento)
 WHERE estado NOT IN('VINCULADO','RETIRADO_VERIFICADO') OR escritura_incierta;
CREATE FUNCTION conservar_identidad_intento_binario_c6() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Los intentos técnicos conservan su antecedente'; END IF;
 IF ROW(NEW.organizacion_id,NEW.operacion,NEW.numero,NEW.fuente,NEW.clave_proveedor,NEW.extension,
   NEW.content_type,NEW.huella,NEW.bytes,NEW.registrado_en)
  IS DISTINCT FROM ROW(OLD.organizacion_id,OLD.operacion,OLD.numero,OLD.fuente,OLD.clave_proveedor,OLD.extension,
   OLD.content_type,OLD.huella,OLD.bytes,OLD.registrado_en)
  THEN RAISE EXCEPTION 'Un intento conserva identidad, fuente y contenido esperado'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER intento_binario_c6_conservar BEFORE UPDATE OR DELETE ON intento_salida_binaria
 FOR EACH ROW EXECUTE FUNCTION conservar_identidad_intento_binario_c6();
