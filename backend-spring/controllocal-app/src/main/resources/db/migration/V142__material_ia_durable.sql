-- C6/CAT-R10-14/E33/E44. Diario técnico de la misma operación financiada en B0.
-- Sin parámetros, perfiles, fondos, proveedor, retención o bytes inventados.
CREATE TABLE material_ia_operacion (
 organizacion_id bigint NOT NULL REFERENCES organizacion(id_organizacion),
 id_operacion uuid NOT NULL,
 id_persona bigint NOT NULL,
 id_rol bigint NOT NULL,
 rol_efectivo varchar(30) NOT NULL,
 sesion_origen varchar(64) NOT NULL,
 accion varchar(30) NOT NULL CHECK(accion IN('REDACTAR_FICHA','ANALIZAR_FOTO','MEJORAR_FOTO')),
 huella_peticion varchar(64) NOT NULL CHECK(huella_peticion ~ '^[0-9a-f]{64}$'),
 solicitud text NOT NULL CHECK(jsonb_typeof(solicitud::jsonb)='object'),
 snapshot text NOT NULL CHECK(jsonb_typeof(snapshot::jsonb)='object'),
 huella_snapshot varchar(64) NOT NULL CHECK(huella_snapshot ~ '^[0-9a-f]{64}$'),
 perfil varchar(60) NOT NULL,
 version_perfil varchar(80) NOT NULL,
 clave_externa varchar(64) NOT NULL UNIQUE CHECK(clave_externa ~ '^[0-9a-f]{64}$'),
 estado varchar(30) NOT NULL CHECK(estado IN('INTENCION','RESERVADA','RECLAMADA','INCIERTA','MEDIDA',
   'CONCILIADA','CONTROLADA','DISPONIBLE','OBSERVADA','RECHAZADA','FALLO_RESULTADO','CANCELADA')),
 medicion text CHECK(medicion IS NULL OR jsonb_typeof(medicion::jsonb)='object'),
 salida text CHECK(salida IS NULL OR jsonb_typeof(salida::jsonb)='object'),
 control_automatico text CHECK(control_automatico IS NULL OR jsonb_typeof(control_automatico::jsonb)='object'),
 resultado text CHECK(resultado IS NULL OR jsonb_typeof(resultado::jsonb)='object'),
 motivo varchar(80),
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0),
 creada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 actualizada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(organizacion_id,id_operacion),
 FOREIGN KEY(organizacion_id,id_persona) REFERENCES persona(organizacion_id,id_persona),
 FOREIGN KEY(organizacion_id,id_rol) REFERENCES persona_rol(organizacion_id,id_persona_rol),
 CHECK((medicion IS NULL)=(salida IS NULL)),
 CHECK(estado NOT IN('MEDIDA','CONCILIADA','CONTROLADA','DISPONIBLE','OBSERVADA','RECHAZADA','FALLO_RESULTADO') OR medicion IS NOT NULL),
 CHECK(estado NOT IN('CONTROLADA','DISPONIBLE','OBSERVADA','RECHAZADA') OR control_automatico IS NOT NULL),
 CHECK(estado<>'DISPONIBLE' OR resultado IS NOT NULL)
);
CREATE TABLE material_ia_evento (
 id_evento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL,
 id_operacion uuid NOT NULL,
 estado varchar(30) NOT NULL,
 evidencia text NOT NULL CHECK(jsonb_typeof(evidencia::jsonb)='object'),
 registrada_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY(organizacion_id,id_operacion) REFERENCES material_ia_operacion(organizacion_id,id_operacion)
);
CREATE INDEX ix_material_ia_pendiente ON material_ia_operacion(organizacion_id,creada_en)
 WHERE estado NOT IN('DISPONIBLE','OBSERVADA','RECHAZADA','CANCELADA');
CREATE FUNCTION conservar_material_ia_c6() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP IN('DELETE','TRUNCATE') THEN
  RAISE EXCEPTION 'La operación IA conserva intención, medición y resultado' USING ERRCODE='23514';
 END IF;
 IF ROW(NEW.organizacion_id,NEW.id_operacion,NEW.id_persona,NEW.id_rol,NEW.rol_efectivo,NEW.sesion_origen,
   NEW.accion,NEW.huella_peticion,NEW.solicitud,NEW.snapshot,NEW.huella_snapshot,NEW.perfil,NEW.version_perfil,
   NEW.clave_externa,NEW.creada_en)
  IS DISTINCT FROM ROW(OLD.organizacion_id,OLD.id_operacion,OLD.id_persona,OLD.id_rol,OLD.rol_efectivo,OLD.sesion_origen,
   OLD.accion,OLD.huella_peticion,OLD.solicitud,OLD.snapshot,OLD.huella_snapshot,OLD.perfil,OLD.version_perfil,
   OLD.clave_externa,OLD.creada_en)
  THEN RAISE EXCEPTION 'Una intención IA conserva actor, fuente y contenido exactos' USING ERRCODE='23514'; END IF;
 IF OLD.medicion IS NOT NULL AND ROW(NEW.medicion,NEW.salida) IS DISTINCT FROM ROW(OLD.medicion,OLD.salida)
  THEN RAISE EXCEPTION 'Se conserva la medición y resultado técnico originales' USING ERRCODE='23514'; END IF;
 IF OLD.control_automatico IS NOT NULL AND NEW.control_automatico IS DISTINCT FROM OLD.control_automatico
  THEN RAISE EXCEPTION 'Se conserva el control automático efectuado' USING ERRCODE='23514'; END IF;
 IF OLD.resultado IS NOT NULL AND NEW.resultado IS DISTINCT FROM OLD.resultado
  THEN RAISE EXCEPTION 'Se conserva el resultado privado de la operación' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER material_ia_conservar BEFORE UPDATE OR DELETE ON material_ia_operacion
 FOR EACH ROW EXECUTE FUNCTION conservar_material_ia_c6();
CREATE TRIGGER material_ia_conservar_truncate BEFORE TRUNCATE ON material_ia_operacion
 FOR EACH STATEMENT EXECUTE FUNCTION conservar_material_ia_c6();
CREATE FUNCTION conservar_evento_material_ia_c6() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Los antecedentes técnicos IA son de sólo anexión' USING ERRCODE='23514'; END;
$$;
CREATE TRIGGER material_ia_evento_conservar BEFORE UPDATE OR DELETE ON material_ia_evento
 FOR EACH ROW EXECUTE FUNCTION conservar_evento_material_ia_c6();
CREATE TRIGGER material_ia_evento_conservar_truncate BEFORE TRUNCATE ON material_ia_evento
 FOR EACH STATEMENT EXECUTE FUNCTION conservar_evento_material_ia_c6();
