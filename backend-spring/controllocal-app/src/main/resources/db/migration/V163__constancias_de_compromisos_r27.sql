-- CAT20.8: evidencia del compromiso expreso. R27 sigue siendo el único seguimiento/calendario.
CREATE TABLE compromiso_seguimiento (
 id_compromiso bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL,id_seguimiento bigint NOT NULL,id_prospeccion bigint NOT NULL,
 referencia uuid NOT NULL UNIQUE,id_responsable_historico bigint NOT NULL,
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0),contenido_json text NOT NULL,
 registrado_en timestamptz NOT NULL,actualizado_en timestamptz NOT NULL,
 UNIQUE(organizacion_id,id_compromiso),
 FOREIGN KEY(organizacion_id,id_prospeccion) REFERENCES prospeccion(organizacion_id,id_prospeccion),
 FOREIGN KEY(organizacion_id,id_responsable_historico) REFERENCES detalle_agente(organizacion_id,id_persona_rol)
);
CREATE INDEX ix_compromiso_seguimiento_contexto ON compromiso_seguimiento(organizacion_id,id_prospeccion,id_seguimiento);
CREATE TABLE compromiso_seguimiento_version (
 organizacion_id bigint NOT NULL,id_compromiso bigint NOT NULL,version bigint NOT NULL CHECK(version>=0),
 contenido_json text NOT NULL,id_rol_actor bigint NOT NULL,registrado_en timestamptz NOT NULL,
 PRIMARY KEY(organizacion_id,id_compromiso,version),
 FOREIGN KEY(organizacion_id,id_compromiso) REFERENCES compromiso_seguimiento(organizacion_id,id_compromiso),
 FOREIGN KEY(organizacion_id,id_rol_actor) REFERENCES persona_rol(organizacion_id,id_persona_rol)
);
CREATE TRIGGER conservar_compromiso_version BEFORE UPDATE OR DELETE ON compromiso_seguimiento_version
 FOR EACH ROW EXECUTE FUNCTION conservar_historia_negociacion();
CREATE TRIGGER conservar_compromiso_version_truncate BEFORE TRUNCATE ON compromiso_seguimiento_version
 FOR EACH STATEMENT EXECUTE FUNCTION conservar_historia_negociacion();
CREATE OR REPLACE FUNCTION exigir_contexto_compromiso_r27() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM seguimiento_prospeccion s WHERE s.organizacion_id=NEW.organizacion_id
   AND s.id_seguimiento=NEW.id_seguimiento AND s.id_prospeccion=NEW.id_prospeccion) THEN
   RAISE EXCEPTION 'El compromiso requiere su seguimiento y prospección del mismo ámbito';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER contexto_compromiso_r27 BEFORE INSERT OR UPDATE ON compromiso_seguimiento
 FOR EACH ROW EXECUTE FUNCTION exigir_contexto_compromiso_r27();
