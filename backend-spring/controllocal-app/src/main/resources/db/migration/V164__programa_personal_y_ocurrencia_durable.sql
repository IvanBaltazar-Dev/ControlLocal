CREATE TABLE plan_tarea_acotado (
 id_plan_tarea bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL,referencia uuid NOT NULL UNIQUE,
 id_persona bigint NOT NULL,id_rol_propietario bigint NOT NULL,
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0),version_mandato bigint NOT NULL DEFAULT 0 CHECK(version_mandato>=0),estado varchar(16) NOT NULL CHECK(estado IN('ACTIVO','PAUSADO','CANCELADO','FINALIZADO')),
 mandato_json text NOT NULL,proxima_en timestamptz NOT NULL,vence_en timestamptz NOT NULL,
 frecuencia_segundos bigint NOT NULL CHECK(frecuencia_segundos>0),max_ocurrencias int NOT NULL CHECK(max_ocurrencias>0),
 ocurrencias int NOT NULL DEFAULT 0 CHECK(ocurrencias>=0 AND ocurrencias<=max_ocurrencias),
 registrado_en timestamptz NOT NULL,actualizado_en timestamptz NOT NULL,causa_estado text,
 UNIQUE(organizacion_id,id_plan_tarea),
 FOREIGN KEY(organizacion_id,id_rol_propietario) REFERENCES detalle_agente(organizacion_id,id_persona_rol)
);
CREATE INDEX ix_programa_personal_dueno ON plan_tarea_acotado(organizacion_id,id_rol_propietario,id_plan_tarea);
CREATE INDEX ix_programa_personal_vencido ON plan_tarea_acotado(proxima_en,id_plan_tarea) WHERE estado='ACTIVO';
CREATE TABLE paso_tarea (
 id_paso_tarea bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL,id_plan_tarea bigint NOT NULL,referencia uuid NOT NULL UNIQUE,
 version_mandato bigint NOT NULL CHECK(version_mandato>=0),programada_en timestamptz NOT NULL,
 estado varchar(20) NOT NULL CHECK(estado IN('RECLAMADA','COMPLETADA','SIN_RESULTADO','PAUSADA','AGOTADA','CANCELADA')),
 intentos int NOT NULL CHECK(intentos>0),reclamo uuid NOT NULL,lease_hasta timestamptz NOT NULL,
 resultado_json text,prueba_json text,causa text,finalizada_en timestamptz,
 UNIQUE(organizacion_id,id_plan_tarea,version_mandato,programada_en),
 FOREIGN KEY(organizacion_id,id_plan_tarea) REFERENCES plan_tarea_acotado(organizacion_id,id_plan_tarea)
);
CREATE UNIQUE INDEX ix_paso_personal_exclusivo ON paso_tarea(organizacion_id,id_plan_tarea) WHERE estado='RECLAMADA';
CREATE INDEX ix_paso_personal_reclamo ON paso_tarea(lease_hasta,id_plan_tarea) WHERE estado='RECLAMADA';
