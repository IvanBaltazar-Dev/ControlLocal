-- RF078/079, CAT-E31. El reporte y su comunicación son hechos distintos.
-- Las filas anteriores permanecen sin referencia/versión acreditadas. No se infiere envío.
ALTER TABLE archivo_encargo DROP CONSTRAINT archivo_encargo_finalidad_check;
ALTER TABLE archivo_encargo ADD CONSTRAINT archivo_encargo_finalidad_check
 CHECK(finalidad IN ('PDF_ENCARGO','ACEPTACION_ENCARGO','TITULARIDAD_ENCARGO',
 'REPRESENTACION_ENCARGO','FIN_ENCARGO','HITO_CONTRACTUAL','COBRO_COMISION','REPORTE_AVANCE'));
ALTER TABLE reporte_propietario ALTER COLUMN canal_envio DROP NOT NULL;
ALTER TABLE reporte_propietario
 ADD COLUMN referencia uuid,
 ADD COLUMN version bigint,
 ADD COLUMN corte timestamptz,
 ADD COLUMN finalidad_reporte text,
 ADD COLUMN contenido_version text,
 ADD COLUMN fuentes_version text,
 ADD COLUMN archivo_previsto_ref uuid;
ALTER TABLE reporte_propietario ADD CONSTRAINT ck_reporte_version_conocida CHECK (
 (referencia IS NULL AND version IS NULL AND corte IS NULL AND finalidad_reporte IS NULL
  AND contenido_version IS NULL AND fuentes_version IS NULL AND archivo_previsto_ref IS NULL)
 OR COALESCE((referencia IS NOT NULL AND version>=0 AND corte IS NOT NULL AND btrim(finalidad_reporte)<>''
  AND jsonb_typeof(contenido_version::jsonb)='object' AND jsonb_typeof(fuentes_version::jsonb)='object'
  AND archivo_previsto_ref IS NOT NULL AND periodo_inicio IS NOT NULL AND periodo_fin IS NOT NULL AND canal_envio IS NULL),FALSE));
CREATE UNIQUE INDEX uq_reporte_referencia_version ON reporte_propietario(organizacion_id,referencia,version) WHERE referencia IS NOT NULL;
CREATE UNIQUE INDEX uq_reporte_archivo_previsto ON reporte_propietario(organizacion_id,archivo_previsto_ref) WHERE archivo_previsto_ref IS NOT NULL;

CREATE FUNCTION conservar_reporte_version_c7() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  IF OLD.referencia IS NOT NULL OR NEW.referencia IS NOT NULL THEN
   RAISE EXCEPTION 'La versión del reporte es inmutable; una nueva preparación conserva otra versión' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 RAISE EXCEPTION 'Se conserva la historia de los reportes' USING ERRCODE='23514';
END; $$;
CREATE TRIGGER conservar_version_reporte BEFORE UPDATE OR DELETE ON reporte_propietario FOR EACH ROW EXECUTE FUNCTION conservar_reporte_version_c7();
CREATE TRIGGER conservar_reportes_truncate BEFORE TRUNCATE ON reporte_propietario FOR EACH STATEMENT EXECUTE FUNCTION conservar_reporte_version_c7();

CREATE FUNCTION validar_secuencia_reporte_c7() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ultima bigint; encargo bigint;
BEGIN
 IF NEW.referencia IS NULL THEN RETURN NEW; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('BROX:REPORTE:'||NEW.organizacion_id||':'||NEW.referencia,0));
 SELECT max(r.version),min(r.id_captacion) INTO ultima,encargo FROM reporte_propietario r
  WHERE r.organizacion_id=NEW.organizacion_id AND r.referencia=NEW.referencia;
 IF (ultima IS NULL AND NEW.version<>0) OR (ultima IS NOT NULL AND (NEW.version<>ultima+1 OR NEW.id_captacion<>encargo)) THEN
  RAISE EXCEPTION 'La versión conserva la secuencia y el Encargo de origen' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER validar_secuencia_reporte BEFORE INSERT ON reporte_propietario FOR EACH ROW EXECUTE FUNCTION validar_secuencia_reporte_c7();

CREATE TABLE comunicacion_reporte (
 id_comunicacion_reporte bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizacion_id bigint NOT NULL,
 referencia uuid NOT NULL UNIQUE,
 id_reporte_propietario bigint NOT NULL,
 version bigint NOT NULL CHECK(version>=0),
 contenido_actual text NOT NULL CHECK(jsonb_typeof(contenido_actual::jsonb)='object'),
 fuente_contacto_actual text NOT NULL CHECK(jsonb_typeof(fuente_contacto_actual::jsonb)='object'),
 registrado_en timestamptz NOT NULL,
 actualizado_en timestamptz NOT NULL,
 UNIQUE(organizacion_id,id_comunicacion_reporte),
 FOREIGN KEY(organizacion_id,id_reporte_propietario) REFERENCES reporte_propietario(organizacion_id,id_reporte_propietario)
);
CREATE TABLE comunicacion_reporte_version (
 organizacion_id bigint NOT NULL,
 id_comunicacion_reporte bigint NOT NULL,
 version bigint NOT NULL CHECK(version>=0),
 contenido text NOT NULL CHECK(jsonb_typeof(contenido::jsonb)='object'),
 fuente_contacto text NOT NULL CHECK(jsonb_typeof(fuente_contacto::jsonb)='object'),
 id_rol_autor bigint NOT NULL,
 registrado_en timestamptz NOT NULL,
 motivo text,
 PRIMARY KEY(organizacion_id,id_comunicacion_reporte,version),
 FOREIGN KEY(organizacion_id,id_comunicacion_reporte) REFERENCES comunicacion_reporte(organizacion_id,id_comunicacion_reporte),
 FOREIGN KEY(organizacion_id,id_rol_autor) REFERENCES detalle_agente(organizacion_id,id_persona_rol)
);
ALTER TABLE comunicacion_reporte ADD CONSTRAINT fk_comunicacion_revision_actual
 FOREIGN KEY(organizacion_id,id_comunicacion_reporte,version)
 REFERENCES comunicacion_reporte_version(organizacion_id,id_comunicacion_reporte,version) DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX ix_comunicacion_reporte_recurso ON comunicacion_reporte(organizacion_id,id_reporte_propietario,id_comunicacion_reporte);

CREATE FUNCTION conservar_comunicacion_reporte_c7() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='comunicacion_reporte' THEN
  IF NEW.id_comunicacion_reporte<>OLD.id_comunicacion_reporte OR NEW.organizacion_id<>OLD.organizacion_id OR NEW.referencia<>OLD.referencia
   OR NEW.id_reporte_propietario<>OLD.id_reporte_propietario OR NEW.registrado_en<>OLD.registrado_en
   OR NEW.version<>OLD.version+1 THEN
   RAISE EXCEPTION 'La comunicación conserva su identidad y versión de reporte; rectificar conserva el antecedente' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 RAISE EXCEPTION 'La comunicación y sus versiones se conservan' USING ERRCODE='23514';
END; $$;
CREATE TRIGGER conservar_raiz_comunicacion BEFORE UPDATE OR DELETE ON comunicacion_reporte FOR EACH ROW EXECUTE FUNCTION conservar_comunicacion_reporte_c7();
CREATE TRIGGER conservar_raiz_comunicacion_truncate BEFORE TRUNCATE ON comunicacion_reporte FOR EACH STATEMENT EXECUTE FUNCTION conservar_comunicacion_reporte_c7();
CREATE TRIGGER conservar_version_comunicacion BEFORE UPDATE OR DELETE ON comunicacion_reporte_version FOR EACH ROW EXECUTE FUNCTION conservar_comunicacion_reporte_c7();
CREATE TRIGGER conservar_version_comunicacion_truncate BEFORE TRUNCATE ON comunicacion_reporte_version FOR EACH STATEMENT EXECUTE FUNCTION conservar_comunicacion_reporte_c7();

CREATE FUNCTION validar_nueva_comunicacion_c7() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.version<>0 OR NOT EXISTS(SELECT 1 FROM reporte_propietario r
  WHERE r.organizacion_id=NEW.organizacion_id AND r.id_reporte_propietario=NEW.id_reporte_propietario
    AND r.referencia IS NOT NULL AND r.version IS NOT NULL) THEN
  RAISE EXCEPTION 'La comunicación inicial requiere una versión de reporte acreditada' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER validar_nueva_comunicacion BEFORE INSERT ON comunicacion_reporte FOR EACH ROW EXECUTE FUNCTION validar_nueva_comunicacion_c7();

CREATE FUNCTION comprobar_proyeccion_comunicacion_c7() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE h comunicacion_reporte_version;
BEGIN
 SELECT * INTO h FROM comunicacion_reporte_version WHERE organizacion_id=NEW.organizacion_id
  AND id_comunicacion_reporte=NEW.id_comunicacion_reporte AND version=NEW.version;
 IF NOT FOUND OR h.contenido::jsonb IS DISTINCT FROM NEW.contenido_actual::jsonb
  OR h.fuente_contacto::jsonb IS DISTINCT FROM NEW.fuente_contacto_actual::jsonb THEN
  RAISE EXCEPTION 'La proyección no coincide con la comunicación conservada' USING ERRCODE='23514';
 END IF;
 RETURN NULL;
END; $$;
CREATE CONSTRAINT TRIGGER comprobar_proyeccion_comunicacion AFTER INSERT OR UPDATE ON comunicacion_reporte
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION comprobar_proyeccion_comunicacion_c7();
