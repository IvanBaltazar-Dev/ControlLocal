-- ---------------------------------------------------------------------
-- V37.8  El invariante pasa de "hay administrador" a "hay administrador
--        OPERATIVO" (D-S0-37)
--
-- La regla de V34 contaba membresias. No basta: una cuenta suspendida,
-- sin factor o con un cambio obligatorio pendiente figura en el recuento
-- y NO puede gobernar.
--
-- OPERATIVO = membresia TENANT_ADMIN activa
--           + credencial activa
--           + factor ACTIVO
--           + sin debe_cambiar_contrasena
--           + sin debe_enrolar_mfa
--
-- Sigue DEFERRABLE INITIALLY DEFERRED por la misma razon que en V34: un
-- relevo pasa por un instante intermedio invalido y debe juzgarse por su
-- RESULTADO. Con esto siguen siendo legales, en cualquier orden:
--   * el primer enrolamiento (la bandera de §2 aun es FALSE);
--   * reemplazar un factor: revocar el viejo y activar el nuevo;
--   * relevar administradores: degradar a uno y promover a otro.
-- Y deja de serlo dejar a la organizacion sin nadie capaz de gobernar.
-- ---------------------------------------------------------------------
DROP TRIGGER tg_usuario_org_exige_administrador ON usuario_organizacion;
DROP FUNCTION exigir_administrador_de_organizacion();

CREATE FUNCTION exigir_administrador_operativo() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    org BIGINT := COALESCE(NEW.organizacion_id, OLD.organizacion_id);
    exige_mfa BOOLEAN;
BEGIN
    IF org IS NULL THEN
        RETURN NULL;
    END IF;

    -- Una organizacion SIN cuentas activas no necesita gobierno: o esta
    -- naciendo o se esta desmontando entera. Exigirselo impediria las dos
    -- cosas, y en particular retirar un tenant de prueba.
    IF NOT EXISTS (
        SELECT 1 FROM usuario_organizacion
         WHERE organizacion_id = org AND estado = 'A'
    ) THEN
        RETURN NULL;
    END IF;

    SELECT o.mfa_gobierno_exigido INTO exige_mfa
      FROM organizacion o WHERE o.id_organizacion = org;

    IF NOT COALESCE(exige_mfa, FALSE) THEN
        -- Antes del primer enrolamiento rige la regla de V34: basta con
        -- que exista gobierno, aunque todavia no tenga segundo factor.
        IF NOT EXISTS (
            SELECT 1 FROM usuario_organizacion
             WHERE organizacion_id = org AND estado = 'A' AND rol = 'TENANT_ADMIN'
        ) THEN
            RAISE EXCEPTION 'Una organizacion no puede quedarse sin administrador '
                            '(organizacion %)', org
                  USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NULL;
    END IF;

    IF NOT EXISTS (
        SELECT 1
          FROM usuario_organizacion uo
          JOIN credencial_usuario cu
            ON cu.id_persona_rol = uo.id_usuario
           AND cu.organizacion_id = uo.organizacion_id
          JOIN factor_autenticacion fa
            ON fa.id_credencial = cu.id_persona_rol
           AND fa.estado = 'ACTIVO'
         WHERE uo.organizacion_id = org
           AND uo.estado = 'A'
           AND uo.rol = 'TENANT_ADMIN'
           AND cu.estado_administrativo = 'A'
           AND NOT cu.debe_cambiar_contrasena
           AND NOT cu.debe_enrolar_mfa
    ) THEN
        RAISE EXCEPTION 'Una organizacion no puede quedarse sin administrador '
                        'operativo (organizacion %)', org
              USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NULL;
END $$;

COMMENT ON FUNCTION exigir_administrador_operativo() IS
    'D-S0-37: red de seguridad del invariante ">= 1 TENANT_ADMIN OPERATIVO". '
    'Se evalua al COMMIT, asi que un relevo o un reemplazo de factor son '
    'validos en cualquier orden mientras el resultado final tenga gobierno. '
    'Antes del primer enrolamiento (organizacion.mfa_gobierno_exigido = FALSE) '
    'se conforma con la regla de V34, para no tapiar el sistema justo cuando '
    'nadie ha podido enrolar todavia.';

CREATE CONSTRAINT TRIGGER tg_usuario_org_exige_administrador
    AFTER INSERT OR UPDATE OR DELETE ON usuario_organizacion
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION exigir_administrador_operativo();

-- Revocar un factor tambien puede dejar sin gobierno. No se vigila el
-- INSERT: crear un factor nunca reduce el recuento, y el primer
-- enrolamiento no debe disparar nada.
CREATE CONSTRAINT TRIGGER tg_factor_exige_administrador
    AFTER UPDATE OR DELETE ON factor_autenticacion
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION exigir_administrador_operativo();

-- Suspender la cuenta o encender un cambio obligatorio degradan igual.
-- El WHEN es lo que mantiene esto fuera del camino caliente: el logout
-- escribe `sesiones_invalidas_desde` en cada salida y NO debe disparar
-- una consulta agregada.
CREATE CONSTRAINT TRIGGER tg_credencial_exige_administrador
    AFTER UPDATE ON credencial_usuario
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (OLD.estado_administrativo IS DISTINCT FROM NEW.estado_administrativo
       OR OLD.debe_cambiar_contrasena IS DISTINCT FROM NEW.debe_cambiar_contrasena
       OR OLD.debe_enrolar_mfa      IS DISTINCT FROM NEW.debe_enrolar_mfa)
    EXECUTE FUNCTION exigir_administrador_operativo();
