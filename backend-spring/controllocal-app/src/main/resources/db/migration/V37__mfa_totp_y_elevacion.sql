-- El unico parcial de V31 decia "un token vivo por credencial", sin mirar el
-- tipo. Con cuatro tipos eso es demasiado: emitir un desafio de MFA mataria
-- una recuperacion de contrasena pendiente —y al reves—, que son flujos
-- independientes. El invariante correcto es el mismo, acotado: **uno vivo por
-- credencial Y TIPO**. Es la misma proteccion (un token viejo filtrado deja de
-- servir en cuanto se emite el bueno de SU tipo) sin acoplar flujos ajenos.
