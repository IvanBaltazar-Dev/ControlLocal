-- ---------------------------------------------------------------------
-- V37.1  Enrolamiento obligatorio para el gobierno (D-S0-25)
-- ---------------------------------------------------------------------
ALTER TABLE credencial_usuario
    ADD COLUMN debe_enrolar_mfa BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN credencial_usuario.debe_enrolar_mfa IS
    'D-S0-25: la sesión existe pero queda CAPADA hasta enrolar el segundo '
    'factor. Gemelo de debe_cambiar_contrasena. Sin esto, exigir MFA a los '
    'administradores el día del despliegue seria una caida de gobierno '
    'autoinfligida: no tienen factor todavia.';

-- Todo administrador vigente queda obligado. No hay ventana en la que un
-- TENANT_ADMIN este sin MFA y sin obligacion de ponerselo.
UPDATE credencial_usuario cu
   SET debe_enrolar_mfa = TRUE
  FROM usuario_organizacion uo
 WHERE uo.id_usuario = cu.id_persona_rol
   AND uo.organizacion_id = cu.organizacion_id
   AND uo.estado = 'A'
   AND uo.rol = 'TENANT_ADMIN';

-- ---------------------------------------------------------------------
-- V37.2  ¿Esta organizacion ya cruzo a MFA de gobierno?
--
-- Es la pieza que hace al invariante de §7 SEGURO EN EL ARRANQUE. Un
-- trigger que exija "siempre >= 1 administrador operativo" deja el
-- sistema tapiado entre el despliegue y el primer enrolamiento: en ese
-- rato NO hay ninguno, porque el backfill de arriba acaba de marcarlos a
-- todos. Y no se puede distinguir "ya estaba roto" de "lo acabas de
-- romper" mirando solo el estado final, que es lo unico que ve un
-- trigger diferido.
--
-- La bandera resuelve esa ambiguedad sin heuristicas: mientras sea
-- FALSE rige la regla de V34 (basta una membresia activa); en cuanto el
-- primer administrador activa su factor pasa a TRUE —en la MISMA
-- transaccion— y desde entonces la organizacion no puede volver a
-- quedarse sin gobierno operativo.
-- ---------------------------------------------------------------------
ALTER TABLE organizacion
    ADD COLUMN mfa_gobierno_exigido BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN organizacion.mfa_gobierno_exigido IS
    'TRUE desde que el primer TENANT_ADMIN activa su factor. Solo la '
    'enciende MfaServiceImpl.confirmar, y nunca se apaga: una organizacion '
    'no des-cruza el umbral de MFA.';

-- ---------------------------------------------------------------------
-- V37.3  El factor
-- ---------------------------------------------------------------------
CREATE TABLE factor_autenticacion (
    id_factor       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT      NOT NULL REFERENCES organizacion (id_organizacion),
    id_credencial   BIGINT      NOT NULL REFERENCES credencial_usuario (id_persona_rol),
    tipo            VARCHAR(10) NOT NULL DEFAULT 'TOTP',

    -- Cifrado REVERSIBLE, no hash: un TOTP hay que poder recalcularlo.
    -- Esa es la diferencia con una contrasena, y la razon por la que la
    -- clave NO puede vivir en esta base — si vive aqui, cifrar no protege
    -- de nada. El tag de GCM va integrado en el criptograma.
    secreto_cifrado BYTEA       NOT NULL,
    nonce           BYTEA       NOT NULL,
    version_clave   SMALLINT    NOT NULL DEFAULT 1,

    -- Explicitos a proposito: si algun dia cambian, se ve en los datos.
    algoritmo       VARCHAR(20) NOT NULL DEFAULT 'HmacSHA1',
    digitos         SMALLINT    NOT NULL DEFAULT 6,
    periodo         SMALLINT    NOT NULL DEFAULT 30,

    estado          VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE',

    -- Anti-replay (D-S0-31). El paso consumido; la validacion es un
    -- UPDATE condicional sobre esta columna, no una comparacion leida
    -- antes: dos peticiones simultaneas aceptarian el mismo codigo.
    ultimo_paso     BIGINT,

    creado_en       TIMESTAMPTZ NOT NULL DEFAULT now(),
    activado_en     TIMESTAMPTZ,
    revocado_en     TIMESTAMPTZ,
    ultimo_uso_en   TIMESTAMPTZ,

    CONSTRAINT ck_factor_tipo   CHECK (tipo IN ('TOTP')),
    CONSTRAINT ck_factor_estado CHECK (estado IN ('PENDIENTE', 'ACTIVO', 'REVOCADO')),
    CONSTRAINT ck_factor_digitos CHECK (digitos BETWEEN 6 AND 8),
    CONSTRAINT ck_factor_periodo CHECK (periodo > 0)
);

-- Un solo factor ACTIVO por credencial. Parcial: los PENDIENTE caducados
-- y los REVOCADO son historia y pueden acumularse.
CREATE UNIQUE INDEX uq_factor_activo_por_credencial
    ON factor_autenticacion (id_credencial) WHERE estado = 'ACTIVO';
CREATE INDEX ix_factor_credencial ON factor_autenticacion (id_credencial, estado);
CREATE INDEX ix_factor_organizacion ON factor_autenticacion (organizacion_id);

COMMENT ON COLUMN factor_autenticacion.ultimo_paso IS
    'D-S0-31: ultimo time-step consumido. Solo se admiten los pasos t y '
    't-1 (D-S0-36): aceptar t+1 dejaria usar un codigo antes de su ventana '
    'y, al sellarlo aqui, tumbaria el codigo actual y el siguiente.';

-- ---------------------------------------------------------------------
-- V37.4  Codigos de respaldo (D-S0-24)
--
-- El IDENTIFICADOR publico es lo que hace viable el hash lento: sin el
-- habria que probar el codigo contra las 8 filas —ocho derivaciones por
-- intento y una palanca de denegacion de servicio regalada—, que es lo
-- que llevaba a usar SHA-256 simple. Con identificador se verifica UNA.
-- ---------------------------------------------------------------------
CREATE TABLE codigo_respaldo_mfa (
    id_codigo       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Lo lleva aunque cuelgue de un factor que ya vive en un tenant: la regla
    -- del proyecto es que TODA fila privada carga el discriminador, y un gate
    -- rompe el build si alguna no lo hace. Ahorrarselo en las hijas es como
    -- se cuela una consulta que cruza corredoras.
    organizacion_id BIGINT      NOT NULL REFERENCES organizacion (id_organizacion),
    id_factor       BIGINT      NOT NULL REFERENCES factor_autenticacion (id_factor),
    identificador VARCHAR(8)   NOT NULL,
    -- PBKDF2 con sal, formato de PasswordHasher. El secreto son 80 bits
    -- aleatorios, asi que el trabajo lento aqui es holgura, no necesidad.
    hash_secreto  VARCHAR(255) NOT NULL,
    creado_en     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    usado_en      TIMESTAMPTZ,
    CONSTRAINT uq_codigo_respaldo_identificador UNIQUE (id_factor, identificador)
);

CREATE INDEX ix_codigo_respaldo_factor ON codigo_respaldo_mfa (id_factor) WHERE usado_en IS NULL;
CREATE INDEX ix_codigo_respaldo_organizacion ON codigo_respaldo_mfa (organizacion_id);

