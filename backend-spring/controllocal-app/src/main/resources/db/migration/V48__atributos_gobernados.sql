-- =====================================================================
-- V48 - M2 del modelo universal: los atributos del inmueble se gobiernan.
--
-- QUE PROBLEMA CIERRA
-- Hoy lo especifico de un subtipo vive en `detalle_local_comercial`: UNA TABLA
-- POR TIPO. Con siete tipos serian siete tablas, siete formularios y siete
-- ramas en cada consulta. Es exactamente lo que el motor de registro (D-E4-2)
-- viene a evitar.
--
-- POR QUE NO UN EAV LIBRE
-- El riesgo del modelo dinamico es que cada quien invente su clave: entonces ni
-- la busqueda ni el matcher pueden comparar dos propiedades, porque una dice
-- `dormitorios` y otra `habitaciones`. Aqui la clave viene de un CATALOGO que
-- declara tipo de dato, unidad, a que tipos de propiedad aplica y en cuales es
-- obligatoria. Sin fila en el catalogo no hay atributo.
--
-- QUE NO HACE ESTA MIGRACION
-- No borra `detalle_local_comercial` ni las columnas de subtipo de `propiedad`
-- (ambientes, frente, zonificacion...). Se conservan porque las entidades las
-- mapean; el codigo migra modulo a modulo y esta tabla ya queda poblada.
-- =====================================================================

-- ---------------------------------------------------------------------
-- El catalogo. `organizacion_id` NULL = atributo del sistema, comun a todos
-- los tenants; una organizacion puede anadir los suyos pero no borrar estos
-- ni redefinir su tipo.
-- ---------------------------------------------------------------------
CREATE TABLE catalogo_atributo (
    id_catalogo_atributo BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id      BIGINT       REFERENCES organizacion (id_organizacion),
    clave                VARCHAR(60)  NOT NULL,
    rotulo               VARCHAR(120) NOT NULL,
    tipo_dato            VARCHAR(10)  NOT NULL,
    unidad               VARCHAR(20),
    -- true = aplica a cualquier tipo de propiedad; si es false, manda la tabla
    -- catalogo_atributo_tipo.
    aplica_todos         BOOLEAN      NOT NULL DEFAULT false,
    del_sistema          BOOLEAN      NOT NULL DEFAULT false,
    orden                INTEGER      NOT NULL DEFAULT 100,
    activo               BOOLEAN      NOT NULL DEFAULT true,
    fecha_creacion       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ck_catalogo_atributo_tipo_dato
        CHECK (tipo_dato IN ('TEXTO', 'ENTERO', 'DECIMAL', 'BOOLEANO', 'LISTA')),
    CONSTRAINT ck_catalogo_atributo_sistema
        CHECK ((del_sistema AND organizacion_id IS NULL)
               OR (NOT del_sistema AND organizacion_id IS NOT NULL))
);

COMMENT ON TABLE catalogo_atributo IS
    'Que caracteristicas puede tener un inmueble, con su tipo y su unidad. D-E4-1 M2.';

-- Una clave por organizacion; los del sistema (org NULL) van aparte. `coalesce`
-- porque en un indice unico dos NULL no chocan entre si.
CREATE UNIQUE INDEX uq_catalogo_atributo_clave
    ON catalogo_atributo (COALESCE(organizacion_id, 0), clave);

-- A que tipos de propiedad aplica cada atributo, y en cuales es obligatorio.
CREATE TABLE catalogo_atributo_tipo (
    id_catalogo_atributo BIGINT      NOT NULL REFERENCES catalogo_atributo (id_catalogo_atributo) ON DELETE CASCADE,
    tipo_propiedad       VARCHAR(1)  NOT NULL,
    requerido            BOOLEAN     NOT NULL DEFAULT false,
    PRIMARY KEY (id_catalogo_atributo, tipo_propiedad),
    -- L local, O oficina, D departamento, C casa, T terreno, A almacen, X otro.
    CONSTRAINT ck_catalogo_atributo_tipo
        CHECK (tipo_propiedad IN ('L', 'O', 'D', 'C', 'T', 'A', 'X'))
);

-- ---------------------------------------------------------------------
-- El valor. Una fila por (propiedad, clave); el valor va en la columna del
-- tipo declarado y solo en una.
-- ---------------------------------------------------------------------
CREATE TABLE atributo_propiedad (
    id_atributo_propiedad BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id       BIGINT        NOT NULL REFERENCES organizacion (id_organizacion),
    id_propiedad          BIGINT        NOT NULL REFERENCES propiedad (id_propiedad),
    clave                 VARCHAR(60)   NOT NULL,
    valor_texto           TEXT,
    valor_numero          NUMERIC(14,4),
    valor_booleano        BOOLEAN,
    fecha_creacion        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_actualizacion   TIMESTAMPTZ,

    -- Exactamente un valor. Un atributo sin responder NO se guarda vacio: se
    -- omite, para que el matcher pueda distinguir "no aplica" de "no lo se".
    CONSTRAINT ck_atributo_un_valor
        CHECK (num_nonnulls(valor_texto, valor_numero, valor_booleano) = 1)
);

COMMENT ON TABLE atributo_propiedad IS
    'Valor de una caracteristica gobernada para una propiedad. D-E4-1 M2.';

CREATE UNIQUE INDEX uq_atributo_propiedad_clave
    ON atributo_propiedad (id_propiedad, clave);
CREATE INDEX ix_atributo_propiedad_organizacion
    ON atributo_propiedad (organizacion_id);
-- El indice que sostiene el matcher: "propiedades con dormitorios >= 3".
CREATE INDEX ix_atributo_propiedad_clave_numero
    ON atributo_propiedad (organizacion_id, clave, valor_numero)
    WHERE valor_numero IS NOT NULL;

-- La clave tiene que existir en el catalogo y aplicar al tipo de la propiedad.
-- Va en trigger y no en FK porque el catalogo admite claves del sistema
-- (organizacion NULL) y de la organizacion, y una FK no puede expresar esa
-- union.
CREATE OR REPLACE FUNCTION exigir_atributo_gobernado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    cat        catalogo_atributo%ROWTYPE;
    tipo_prop  varchar(1);
BEGIN
    SELECT * INTO cat
      FROM catalogo_atributo
     WHERE clave = NEW.clave
       AND activo
       AND (organizacion_id IS NULL OR organizacion_id = NEW.organizacion_id)
     ORDER BY organizacion_id NULLS LAST
     LIMIT 1;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El atributo "%" no esta en el catalogo', NEW.clave
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    SELECT tipo_inmueble INTO tipo_prop FROM propiedad WHERE id_propiedad = NEW.id_propiedad;

    IF NOT cat.aplica_todos
       AND NOT EXISTS (SELECT 1 FROM catalogo_atributo_tipo t
                        WHERE t.id_catalogo_atributo = cat.id_catalogo_atributo
                          AND t.tipo_propiedad = tipo_prop) THEN
        RAISE EXCEPTION 'El atributo "%" no aplica a una propiedad de tipo %', NEW.clave, tipo_prop
            USING ERRCODE = 'check_violation';
    END IF;

    -- El valor tiene que estar en la columna que corresponde a su tipo.
    IF cat.tipo_dato IN ('ENTERO', 'DECIMAL') AND NEW.valor_numero IS NULL THEN
        RAISE EXCEPTION 'El atributo "%" es numerico y llego sin valor_numero', NEW.clave
            USING ERRCODE = 'check_violation';
    ELSIF cat.tipo_dato = 'BOOLEANO' AND NEW.valor_booleano IS NULL THEN
        RAISE EXCEPTION 'El atributo "%" es booleano y llego sin valor_booleano', NEW.clave
            USING ERRCODE = 'check_violation';
    ELSIF cat.tipo_dato IN ('TEXTO', 'LISTA') AND NEW.valor_texto IS NULL THEN
        RAISE EXCEPTION 'El atributo "%" es de texto y llego sin valor_texto', NEW.clave
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_atributo_gobernado
    BEFORE INSERT OR UPDATE ON atributo_propiedad
    FOR EACH ROW
    EXECUTE FUNCTION exigir_atributo_gobernado();

