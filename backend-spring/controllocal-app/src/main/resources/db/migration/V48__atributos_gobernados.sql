-- ---------------------------------------------------------------------
-- Backfill: lo que ya esta escrito en columnas pasa a ser atributo.
--
-- No se inventa nada: cada INSERT copia una columna que ya tiene valor. Las
-- columnas de origen SE CONSERVAN hasta que el codigo deje de leerlas.
-- Idempotente por el ON CONFLICT.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    total bigint;
BEGIN
    -- Numericos de `propiedad`.
    INSERT INTO atributo_propiedad (organizacion_id, id_propiedad, clave, valor_numero)
    SELECT p.organizacion_id, p.id_propiedad, v.clave, v.valor
      FROM propiedad p
      CROSS JOIN LATERAL (VALUES
            ('metraje_total',       p.metraje),
            ('antiguedad_anios',    p.antiguedad_anios::numeric),
            ('estacionamientos',    p.numero_estacionamientos::numeric),
            ('ambientes',           p.ambientes::numeric),
            ('frente',              p.frente),
            ('cuota_mantenimiento', p.cuota_mantenimiento)
           ) AS v(clave, valor)
     WHERE v.valor IS NOT NULL
    ON CONFLICT (id_propiedad, clave) DO NOTHING;

    -- Textos de `propiedad`.
    INSERT INTO atributo_propiedad (organizacion_id, id_propiedad, clave, valor_texto)
    SELECT p.organizacion_id, p.id_propiedad, v.clave, v.valor
      FROM propiedad p
      CROSS JOIN LATERAL (VALUES
            ('zonificacion', p.zonificacion),
            ('piso',         p.piso)
           ) AS v(clave, valor)
     WHERE v.valor IS NOT NULL AND btrim(v.valor) <> ''
    ON CONFLICT (id_propiedad, clave) DO NOTHING;

    -- Lo especifico del local comercial.
    INSERT INTO atributo_propiedad (organizacion_id, id_propiedad, clave, valor_texto)
    SELECT d.organizacion_id, d.id_propiedad, 'rubro_permitido', d.rubro_permitido
      FROM detalle_local_comercial d
     WHERE d.rubro_permitido IS NOT NULL AND btrim(d.rubro_permitido) <> ''
    ON CONFLICT (id_propiedad, clave) DO NOTHING;

    INSERT INTO atributo_propiedad (organizacion_id, id_propiedad, clave, valor_numero)
    SELECT d.organizacion_id, d.id_propiedad, 'carga_electrica_kw', d.carga_electrica_kw
      FROM detalle_local_comercial d
     WHERE d.carga_electrica_kw IS NOT NULL
    ON CONFLICT (id_propiedad, clave) DO NOTHING;

    INSERT INTO atributo_propiedad (organizacion_id, id_propiedad, clave, valor_booleano)
    SELECT d.organizacion_id, d.id_propiedad, 'apto_licencia_funcionamiento', d.apto_licencia_funcionamiento
      FROM detalle_local_comercial d
     WHERE d.apto_licencia_funcionamiento IS NOT NULL
    ON CONFLICT (id_propiedad, clave) DO NOTHING;

    SELECT count(*) INTO total FROM atributo_propiedad;
    RAISE NOTICE 'V48: catalogo con % atributos del sistema; % valores migrados',
        (SELECT count(*) FROM catalogo_atributo WHERE del_sistema), total;
END $$;
