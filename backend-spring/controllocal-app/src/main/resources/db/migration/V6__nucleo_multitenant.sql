CREATE TABLE aviso_privacidad_version (
    id_aviso        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         VARCHAR(20)  NOT NULL UNIQUE,
    contenido_hash  VARCHAR(64)  NOT NULL,
    contenido       TEXT         NOT NULL,
    vigente_desde   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    vigente_hasta   TIMESTAMPTZ
);

CREATE TABLE evidencia_autorizacion (
    id_evidencia        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal               VARCHAR(20)  NOT NULL,   -- WEB | WHATSAPP | …
    mensaje_id          VARCHAR(100),
    ip                  VARCHAR(45),
    user_agent          VARCHAR(300),
    phone_number_id     VARCHAR(60),
    whatsapp_message_id VARCHAR(100),
    fecha_hora          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    texto_mostrado      TEXT,
    respuesta_recibida  TEXT
);

-- Registro APPEND-ONLY: el estado vigente se deriva por proyeccion, no se
-- destruye el evento anterior (trazabilidad completa del consentimiento).
CREATE TABLE autorizacion_tratamiento_evento (
    id_evento        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id  BIGINT       NOT NULL REFERENCES organizacion (id_organizacion),
    id_persona       BIGINT       NOT NULL,
    finalidad_codigo VARCHAR(40)  NOT NULL REFERENCES finalidad_tratamiento (codigo),
    evento           VARCHAR(24)  NOT NULL,
    base_juridica    VARCHAR(24)  NOT NULL,
    version_aviso    VARCHAR(20),
    ocurrido_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    id_evidencia     BIGINT REFERENCES evidencia_autorizacion (id_evidencia),
    CONSTRAINT ck_autorizacion_evento CHECK (
        evento IN ('INFORMADO', 'OTORGADO', 'RECHAZADO', 'REVOCADO',
                   'REOTORGADO', 'EXPIRADO', 'CAMBIO_BASE_JURIDICA')
    ),
    CONSTRAINT ck_autorizacion_base CHECK (
        base_juridica IN ('CONSENTIMIENTO', 'RELACION_CONTRACTUAL',
                          'OBLIGACION_LEGAL', 'OTRA_EXCEPCION_LEGAL')
    ),
    CONSTRAINT fk_autorizacion_persona_org
        FOREIGN KEY (organizacion_id, id_persona) REFERENCES persona (organizacion_id, id_persona)
);
CREATE INDEX ix_autorizacion_persona
    ON autorizacion_tratamiento_evento (organizacion_id, id_persona, finalidad_codigo, ocurrido_en DESC);
