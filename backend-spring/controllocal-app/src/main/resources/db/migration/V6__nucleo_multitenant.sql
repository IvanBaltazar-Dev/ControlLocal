-- V6.1  Organizacion + tenant de legado
-- ---------------------------------------------------------------------
CREATE TABLE organizacion (
    id_organizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(30)  NOT NULL UNIQUE,
    nombre          VARCHAR(150) NOT NULL,
    estado          VARCHAR(1)   NOT NULL DEFAULT 'A',
    fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_organizacion_estado CHECK (estado IN ('A', 'I'))
);

-- SIVAN es la empresa duena de la plataforma, NO un tenant: el legado es BROX_LEGACY.
INSERT INTO organizacion (codigo, nombre) VALUES ('BROX_LEGACY', 'Organizacion de legado');

-- ---------------------------------------------------------------------
-- V6.2  organizacion_id NULLABLE -> backfill -> NOT NULL (14 privadas)
--   Patron por tabla: ADD COLUMN null -> UPDATE al legado -> SET NOT NULL.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    legado    BIGINT := (SELECT id_organizacion FROM organizacion WHERE codigo = 'BROX_LEGACY');
    privada   TEXT;
    privadas  TEXT[] := ARRAY[
        'persona', 'persona_rol', 'credencial_usuario', 'detalle_broker',
        'detalle_agente', 'supervision_agente', 'historial_estado',
        'propiedad', 'detalle_local_comercial', 'foto_propiedad',
        'precio_propiedad', 'publicacion', 'captacion', 'prospeccion',
        'reasignacion_captacion'
    ];
BEGIN
    FOREACH privada IN ARRAY privadas LOOP
        EXECUTE format(
            'ALTER TABLE %I ADD COLUMN organizacion_id BIGINT REFERENCES organizacion (id_organizacion)',
            privada);
        EXECUTE format('UPDATE %I SET organizacion_id = %L WHERE organizacion_id IS NULL',
            privada, legado);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN organizacion_id SET NOT NULL', privada);
        -- Nombre del indice por concatenacion (%s), tabla como identificador (%I).
        EXECUTE format('CREATE INDEX ix_%s_organizacion ON %I (organizacion_id)', privada, privada);
    END LOOP;
END $$;

