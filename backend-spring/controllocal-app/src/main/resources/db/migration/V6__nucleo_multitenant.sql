    FOREIGN KEY (organizacion_id, id_captacion) REFERENCES captacion (organizacion_id, id_captacion);

-- ---------------------------------------------------------------------
-- V6.5  Membresia del usuario interno (D-26). La CUENTA de acceso global
--        (D-22) se separa en el corte de GlassFish; aqui la membresia ya
--        existe para que las asignaciones referencien la organizacion.
--   id_usuario = referencia a la futura cuenta global; durante la
--   convivencia apunta al persona_rol del usuario interno (1:1 con el login).
-- ---------------------------------------------------------------------
CREATE TABLE usuario_organizacion (
    id_usuario_organizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id  BIGINT      NOT NULL REFERENCES organizacion (id_organizacion),
    id_usuario       BIGINT      NOT NULL,   -- cuenta global (transitorio: id_persona_rol del interno)
    rol              VARCHAR(20) NOT NULL,   -- BROKER | AGENTE | ADMIN (banda operativa)
    nombre_visible   VARCHAR(120),
    estado           VARCHAR(1)  NOT NULL DEFAULT 'A',
    -- Vinculo OPCIONAL a una persona del MISMO tenant, solo si el usuario
    -- tambien es actor del dominio (agente que alquila para si). No cambia permisos.
    id_persona       BIGINT,
    fecha_alta       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_org_estado CHECK (estado IN ('A', 'I')),
    CONSTRAINT uq_usuario_org UNIQUE (organizacion_id, id_usuario),
    CONSTRAINT fk_usuario_org_persona_org
        FOREIGN KEY (organizacion_id, id_persona) REFERENCES persona (organizacion_id, id_persona)
);
CREATE INDEX ix_usuario_org_organizacion ON usuario_organizacion (organizacion_id, estado);

-- Backfill: una membresia por usuario interno existente (credencial_usuario),
-- con la banda operativa segun su detalle (ADMIN si es_administrador, si no BROKER/AGENTE).
INSERT INTO usuario_organizacion (organizacion_id, id_usuario, rol, nombre_visible, id_persona)
SELECT cu.organizacion_id, cu.id_persona_rol,
       CASE
           WHEN db.es_administrador THEN 'ADMIN'
           WHEN db.id_persona_rol IS NOT NULL THEN 'BROKER'
           ELSE 'AGENTE'
       END,
       per.nombres_o_razon_social,
       pr.id_persona
FROM credencial_usuario cu
JOIN persona_rol pr ON pr.id_persona_rol = cu.id_persona_rol
JOIN persona     per ON per.id_persona = pr.id_persona
LEFT JOIN detalle_broker db ON db.id_persona_rol = cu.id_persona_rol;

-- ---------------------------------------------------------------------
-- V6.6  Consentimiento granular (D-25): finalidad + base juridica +
--        estado + version del aviso + evidencia + vigencia. Contrato
--        listo; los flujos conversacionales de KAIROS llegan despues.
