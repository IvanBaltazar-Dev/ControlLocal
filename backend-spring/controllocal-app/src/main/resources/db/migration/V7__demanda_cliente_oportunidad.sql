-- =====================================================================
-- V7: vertical F3 - DEMANDA (contrato congelado en
-- docs/ai/contrato-congelado-f3-demanda.md).
--  * El cliente interesado es un ROL de persona (Party-Role), igual que
--    agente/broker/propietario: detalle_cliente cuelga de persona_rol con
--    tipo_rol='CLIENTE'. No se duplican nombre/documento/contacto.
--  * oportunidad_comercial es la entidad-HUB: conserva la trazabilidad
--    aunque el interesado nunca llegue a presentar una solicitud.
--  * interaccion_comercial es la bitacora POLIMORFICA: cuelga de UNA de
--    cuatro entidades segun 'contexto', con CHECK que lo garantiza.
--  * Todo es privado del tenant (V6): organizacion_id NOT NULL sin
--    DEFAULT, unicidades por organizacion y FK compuestas con el tenant.
--  * Los codigos de entidad_tipo (OPORTUNIDAD, VISITA, CLIENTE_INTERESADO,
--    REQUERIMIENTO) ya estan sembrados desde V2.
--  * Vocabulario del cable: estado oportunidad A/S/N/F/X, visita
--    P/G/C/N/R. OJO: requerimiento y resultado de interaccion NO son
--    CHAR(1) — la v1 emite el nombre del enum (ver §1 del contrato).
-- =====================================================================

