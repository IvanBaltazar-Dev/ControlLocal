-- ---------------------------------------------------------------------
-- 6. La fuente TEXTUAL de las dos transcripciones documentadas.
--    (Va DENTRO del INSERT de arriba, no en un UPDATE posterior: la tabla es
--     append-only y su trigger rechaza el UPDATE, con razon.)
--
-- `LOC-D001` y `LOC-0002` recibieron su `tipo_acceso` transcribiendo LITERALMENTE
-- una frase que ya estaba en `propiedad.descripcion` -- «Local a pie de calle con
-- vitrina» y «Local en galeria del centro» --, no capturandolo en una visita.
-- El evento de esa edicion demuestra el ACTO (quien, cuando, por que canal) y no
-- dice nada de la FUENTE, asi que sin esto los dos valores quedarian
-- indistinguibles de uno observado.
--
-- **Aqui no se miente en ninguna direccion.** Se afirma de donde se copio el
-- texto -- que es comprobable, y esta migracion LO COMPRUEBA antes de afirmarlo:
-- si la descripcion ya no contiene la frase, no anade nada -- y NO se afirma
-- quien origino esa descripcion, que nadie sabe. Por eso `naturaleza` sigue
-- ausente: no se les atribuye DECLARADO, porque el sistema no puede demostrar
-- que hubiera una declaracion de contraparte.
--
-- La lista es corta y explicita a proposito, como el `codigo IN (...)` de V14 y
-- V76: son dos hechos concretos de una cartera concreta, no una regla.
--
-- ---------------------------------------------------------------------
-- 7. Lo que esta migracion NO hace, dicho para que no se busque.
--
-- No anade ninguna columna a `atributo_propiedad` ni a `atributo_encargo`: esas
-- dos tablas siguen siendo el ESTADO VIGENTE y no cambian ni una fila.
--
-- No pone la procedencia NOT NULL en ninguna de las cuatro tablas de valor, y
-- es una DECISION, no una concesion: seis suites E2E y `gate-modelo-universal.sql`
-- escriben por SQL directo, deliberadamente, para probar los triggers de la base
-- intentando romperlos. Un NOT NULL alli convertiria el gate en rehen del
-- servicio. La invariante "toda escritura gobernada deja linaje" se sostiene EN
-- LA FRONTERA DEL SERVICIO, con un test de arquitectura -- y lo que un INSERT
-- manual escriba no lo cubre nadie, ni aqui ni en el codigo.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    sembradas bigint;
    huerfanas bigint;
BEGIN
    SELECT count(*) INTO sembradas FROM rastro_valor_gobernado;
    SELECT count(*) INTO huerfanas FROM rastro_valor_gobernado WHERE naturaleza IS NOT NULL;
    IF huerfanas > 0 THEN
        RAISE EXCEPTION 'V83: % filas de genesis con naturaleza declarada. La genesis '
                        'nunca dice COMO se conocio el hecho.', huerfanas;
    END IF;
    RAISE NOTICE 'V83: linaje de valor gobernado en marcha; % filas de genesis demostrable, '
                 'frontera en %', sembradas, frontera_de_linaje();
END $$;
