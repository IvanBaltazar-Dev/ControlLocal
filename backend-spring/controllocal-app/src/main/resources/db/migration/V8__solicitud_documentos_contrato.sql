-- ---------------------------------------------------------------------
-- Solicitud de alquiler: la oferta formal del interesado sobre la
-- oportunidad. UNA por oportunidad (unicidad del cable v1).
-- La captacion NO se duplica aqui: se deriva por la oportunidad.
-- ---------------------------------------------------------------------
CREATE TABLE solicitud_alquiler (
    id_solicitud               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id            BIGINT        NOT NULL REFERENCES organizacion (id_organizacion),
    codigo_solicitud           VARCHAR(20)   NOT NULL,
    fecha_registro             DATE          NOT NULL,
    monto_propuesto            NUMERIC(12,2) NOT NULL,
    plazo_tentativo            VARCHAR(50),
    observaciones              TEXT,
    estado                     VARCHAR(1)    NOT NULL,
    fecha_actualizacion_estado TIMESTAMPTZ,
    fecha_vigencia_oferta      DATE,
    -- Condiciones del trato que el broker evalua y que el contrato hereda al cerrar.
    plazo_contrato_meses       INTEGER,
    fecha_inicio_contrato      DATE,
    forma_pago                 VARCHAR(20),
    meses_garantia             INTEGER,
    meses_adelanto             INTEGER,
    id_oportunidad             BIGINT        NOT NULL REFERENCES oportunidad_comercial (id_oportunidad),
    id_rol_agente              BIGINT        NOT NULL REFERENCES detalle_agente (id_persona_rol),
    fecha_creacion             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_actualizacion        TIMESTAMPTZ,
    -- G registrada, E en evaluacion, O observada, A aprobada, R rechazada,
    -- D desistida, C cerrada (su alquiler se concreto en contrato).
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('G', 'E', 'O', 'A', 'R', 'D', 'C')),
    CONSTRAINT ck_solicitud_monto CHECK (monto_propuesto >= 0),
    CONSTRAINT ck_solicitud_plazo CHECK (plazo_contrato_meses IS NULL OR plazo_contrato_meses > 0),
    CONSTRAINT ck_solicitud_meses CHECK (
        (meses_garantia IS NULL OR meses_garantia >= 0)
        AND (meses_adelanto IS NULL OR meses_adelanto >= 0)),
    -- Una sola solicitud por oportunidad (cable v1: id_oportunidad UNIQUE).
    CONSTRAINT uq_solicitud_oportunidad UNIQUE (id_oportunidad),
    -- El codigo SOL-yyMMddHHmmss es unico DENTRO del tenant (D-F4-4).
    CONSTRAINT uq_solicitud_codigo UNIQUE (organizacion_id, codigo_solicitud),
    CONSTRAINT uq_solicitud_org UNIQUE (organizacion_id, id_solicitud),
    CONSTRAINT fk_solicitud_oportunidad_org FOREIGN KEY (organizacion_id, id_oportunidad)
        REFERENCES oportunidad_comercial (organizacion_id, id_oportunidad),
    CONSTRAINT fk_solicitud_agente_org FOREIGN KEY (organizacion_id, id_rol_agente)
        REFERENCES detalle_agente (organizacion_id, id_persona_rol)
);

CREATE INDEX ix_solicitud_agente ON solicitud_alquiler (organizacion_id, id_rol_agente);
CREATE INDEX ix_solicitud_estado ON solicitud_alquiler (organizacion_id, estado);

-- ---------------------------------------------------------------------
-- Documento entregado para la solicitud. Nace Registrado con revision
-- Pendiente; el broker lo deja Validado u Observado.
-- ---------------------------------------------------------------------
CREATE TABLE documento_solicitud (
    id_documento                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id             BIGINT       NOT NULL REFERENCES organizacion (id_organizacion),
    id_solicitud                BIGINT       NOT NULL REFERENCES solicitud_alquiler (id_solicitud) ON DELETE CASCADE,
    id_tipo_documento_requerido BIGINT       NOT NULL REFERENCES tipo_documento_requerido (id_tipo_documento_requerido),
    nombre_archivo              VARCHAR(255) NOT NULL,
    -- Clave del almacen hibrido (S3 o disco), no una ruta del sistema.
    ruta_archivo                VARCHAR(255),
    fecha_entrega               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    estado                      VARCHAR(1)   NOT NULL,
    resultado_revision          VARCHAR(1),
    observaciones               TEXT,
    CONSTRAINT ck_documento_estado CHECK (estado IN ('R', 'O', 'V')),
    CONSTRAINT ck_documento_revision CHECK (
        resultado_revision IS NULL OR resultado_revision IN ('P', 'C', 'O')),
    -- Un documento observado SIEMPRE lleva el porque (MEJ-03, como en captaciones).
    CONSTRAINT ck_documento_observacion CHECK (
        resultado_revision <> 'O' OR (observaciones IS NOT NULL AND btrim(observaciones) <> '')),
    CONSTRAINT uq_documento_org UNIQUE (organizacion_id, id_documento),
    CONSTRAINT fk_documento_solicitud_org FOREIGN KEY (organizacion_id, id_solicitud)
        REFERENCES solicitud_alquiler (organizacion_id, id_solicitud)
);

CREATE INDEX ix_documento_solicitud ON documento_solicitud (organizacion_id, id_solicitud);
CREATE INDEX ix_documento_tipo ON documento_solicitud (id_tipo_documento_requerido);

-- ---------------------------------------------------------------------
-- Evaluacion del broker. NO es transicionable: es un evento con
-- resultado que MUEVE la solicitud (aprobar / rechazar / observar).
-- El tipo se DERIVA del resultado, el broker no lo elige.
-- ---------------------------------------------------------------------
CREATE TABLE evaluacion_solicitud (
    id_evaluacion    BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id  BIGINT      NOT NULL REFERENCES organizacion (id_organizacion),
    id_solicitud     BIGINT      NOT NULL REFERENCES solicitud_alquiler (id_solicitud),
    id_rol_broker    BIGINT      NOT NULL REFERENCES detalle_broker (id_persona_rol),
    fecha_evaluacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    resultado        VARCHAR(1)  NOT NULL,
    tipo_evaluacion  VARCHAR(1)  NOT NULL,
    observaciones    TEXT,
    CONSTRAINT ck_evaluacion_resultado CHECK (resultado IN ('A', 'R', 'O')),
    CONSTRAINT ck_tipo_evaluacion CHECK (tipo_evaluacion IN ('P', 'O', 'F')),
    -- El tipo se deriva del resultado (cable v1): observada => OBSERVACION,
    -- aprobada/rechazada => FINAL. El CHECK lo garantiza en la BD.
    CONSTRAINT ck_evaluacion_tipo_derivado CHECK (
        (resultado = 'O' AND tipo_evaluacion = 'O')
        OR (resultado IN ('A', 'R') AND tipo_evaluacion = 'F')),
    CONSTRAINT uq_evaluacion_org UNIQUE (organizacion_id, id_evaluacion),
    CONSTRAINT fk_evaluacion_solicitud_org FOREIGN KEY (organizacion_id, id_solicitud)
        REFERENCES solicitud_alquiler (organizacion_id, id_solicitud),
    CONSTRAINT fk_evaluacion_broker_org FOREIGN KEY (organizacion_id, id_rol_broker)
        REFERENCES detalle_broker (organizacion_id, id_persona_rol)
);

-- "Solo una evaluacion FINAL por solicitud": la v1 lo resolvia con una
-- columna generada + UNIQUE; en Postgres es un unico parcial nativo.
CREATE UNIQUE INDEX uq_evaluacion_final_por_solicitud
    ON evaluacion_solicitud (id_solicitud) WHERE tipo_evaluacion = 'F';

CREATE INDEX ix_evaluacion_solicitud ON evaluacion_solicitud (organizacion_id, id_solicitud);
CREATE INDEX ix_evaluacion_broker ON evaluacion_solicitud (organizacion_id, id_rol_broker);

-- ---------------------------------------------------------------------
-- Contrato de alquiler: vinculo + formalizacion. Las condiciones del
-- trato viven en la solicitud, no se copian.
-- ---------------------------------------------------------------------
CREATE TABLE contrato_alquiler (
    id_contrato_alquiler BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id      BIGINT      NOT NULL REFERENCES organizacion (id_organizacion),
    id_oportunidad       BIGINT      NOT NULL REFERENCES oportunidad_comercial (id_oportunidad),
    id_solicitud         BIGINT      REFERENCES solicitud_alquiler (id_solicitud),
    fecha_cierre         DATE        NOT NULL,
    estado_contrato      VARCHAR(1)  NOT NULL,
    incidencias          TEXT,
    fecha_creacion       TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ,
    CONSTRAINT ck_contrato_estado CHECK (estado_contrato IN ('P', 'D', 'V', 'R', 'F', 'S', 'A')),
    -- Un contrato por oportunidad y por solicitud (cable v1: ambas UNIQUE).
    CONSTRAINT uq_contrato_oportunidad UNIQUE (id_oportunidad),
    CONSTRAINT uq_contrato_solicitud UNIQUE (id_solicitud),
    CONSTRAINT uq_contrato_org UNIQUE (organizacion_id, id_contrato_alquiler),
    CONSTRAINT fk_contrato_oportunidad_org FOREIGN KEY (organizacion_id, id_oportunidad)
        REFERENCES oportunidad_comercial (organizacion_id, id_oportunidad),
    CONSTRAINT fk_contrato_solicitud_org FOREIGN KEY (organizacion_id, id_solicitud)
        REFERENCES solicitud_alquiler (organizacion_id, id_solicitud)
);

CREATE INDEX ix_contrato_organizacion ON contrato_alquiler (organizacion_id);

-- ---------------------------------------------------------------------
-- Liquidacion de comision. Nace PENDIENTE con la bruta (% pactado x un
-- mes de renta); el broker supervisor define despues el monto del agente
-- y el sistema calcula el de la empresa.
-- estado y forma_pago viajan con el NOMBRE del enum, no CHAR(1).
-- ---------------------------------------------------------------------
CREATE TABLE comision_liquidacion (
    id_comision_liquidacion BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id         BIGINT        NOT NULL REFERENCES organizacion (id_organizacion),
    id_contrato_alquiler    BIGINT        NOT NULL REFERENCES contrato_alquiler (id_contrato_alquiler),
    monto                   NUMERIC(12,2) NOT NULL,
    moneda                  VARCHAR(10)   NOT NULL,
    monto_agente            NUMERIC(12,2),
    monto_empresa           NUMERIC(12,2),
    fecha_cobro             DATE,
    forma_pago              VARCHAR(20),
    estado                  VARCHAR(20)   NOT NULL,
    CONSTRAINT ck_comision_moneda CHECK (moneda IN ('PEN', 'USD')),
    CONSTRAINT ck_comision_estado CHECK (estado IN ('PENDIENTE', 'PARCIAL', 'COBRADA', 'ANULADA')),
    CONSTRAINT ck_comision_forma_pago CHECK (
        forma_pago IS NULL OR forma_pago IN (
            'TRANSFERENCIA', 'DEPOSITO_BANCARIO', 'EFECTIVO', 'CHEQUE', 'OTRO')),
    CONSTRAINT ck_comision_montos CHECK (
        monto >= 0
        AND (monto_agente IS NULL OR monto_agente >= 0)
        AND (monto_empresa IS NULL OR monto_empresa >= 0)),
    -- Una liquidacion por contrato.
    CONSTRAINT uq_comision_contrato UNIQUE (id_contrato_alquiler),
    CONSTRAINT uq_comision_org UNIQUE (organizacion_id, id_comision_liquidacion),
    CONSTRAINT fk_comision_contrato_org FOREIGN KEY (organizacion_id, id_contrato_alquiler)
        REFERENCES contrato_alquiler (organizacion_id, id_contrato_alquiler)
);

CREATE INDEX ix_comision_estado ON comision_liquidacion (organizacion_id, estado);

