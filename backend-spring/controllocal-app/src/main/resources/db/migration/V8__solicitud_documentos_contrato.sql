-- =====================================================================
-- V8: vertical F4 - SOLICITUD, DOCUMENTOS, EVALUACION, CONTRATO Y
-- COMISION (contrato congelado en
-- docs/ai/contrato-congelado-f4-solicitud.md).
--  * Es la vertical que CIERRA el ciclo: el contrato registrado sobre una
--    solicitud aprobada es lo que cierra la oportunidad como exitosa
--    (por eso /oportunidades/{id}/cierre-exitoso responde 400 para
--    siempre; el cierre no lo produce un boton).
--  * tipo_documento_requerido es CATALOGO GLOBAL (como distrito): no
--    lleva organizacion_id y debe declararse global en
--    ArquitecturaTenancyTest. El resto es privado del tenant (V6):
--    organizacion_id NOT NULL sin DEFAULT, unicidades por organizacion y
--    FK compuestas con el tenant.
--  * Los ids 1..8 del catalogo son PARTE DEL CABLE: el enum
--    TipoDocumentoSolicitud de la v1 mapea codigo <-> idCatalogo por
--    posicion (I=1, R=2, V=3, P=4, E=5, G=6, D=7, O=8). No reordenar.
--  * Vocabulario del cable: solicitud G/E/O/A/R/D/C, documento R/O/V con
--    revision P/C/O, evaluacion A/R/O y tipo P/O/F, contrato
--    P/D/V/R/F/S/A. OJO: comision y forma de pago NO son CHAR(1) — la v1
--    emite el NOMBRE del enum (ver §1 del contrato), igual que F3.
--  * Los codigos de entidad_tipo (SOLICITUD_ALQUILER, DOCUMENTO_SOLICITUD,
--    EVALUACION, CONTRATO_ALQUILER, COMISION_LIQUIDACION) ya estan
--    sembrados desde V2.
-- =====================================================================

