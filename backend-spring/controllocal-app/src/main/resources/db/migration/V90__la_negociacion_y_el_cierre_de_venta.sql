-- =====================================================================
-- V90 - WP-A: la oferta, la contraoferta y el cierre de una venta.
--
-- QUE PROBLEMA CIERRA
-- BROX sabia captar, publicar y alquilar. De la NEGOCIACION no guardaba nada:
-- una propiedad pasaba de "publicada a 180.000" a "vendida" sin una sola fila
-- que dijera a cuanto se ofrecio, cuantas veces se contraofertó ni por que se
-- cayo. La serie economica tenia hitos 'O' (ofertado) y 'A' (aceptado) en su
-- CHECK desde V4 y NADIE los escribia: eran vocabulario sin productor.
--
-- LO QUE SE ANADE, Y DONDE VIVE CADA COSA
--   oferta                 la mesa de negociacion, colgada de la OPORTUNIDAD
--                          (quien negocia con quien) y del ENCARGO (sobre que).
--   precio_propiedad.id_oferta  para que la serie economica se pueda leer por
--                          encargo Y por mesa. Dos negociaciones sobre la misma
--                          propiedad son dos oportunidades y dos series
--                          distinguibles.
--   contrato_compraventa   el cierre de una VENTA.
--   motivo_no_continuidad  cuatro razones mas, las que una venta necesita y el
--                          vocabulario de alquiler no sabia decir.
--
-- POR QUE UNA TABLA `contrato_compraventa` Y NO REUTILIZAR `contrato_alquiler`
-- `contrato_alquiler` NO es generico: tiene `renta_contractual`,
-- `fecha_fin_contrato`, `id_contrato_anterior` (la renovacion) y de el cuelga
-- `comision_liquidacion` por FK. Meter una compraventa ahi obligaria a dejar
-- esas cuatro en NULL, a debilitar sus CHECK y a que cada consulta del ciclo de
-- alquiler preguntara "¿y si es una venta?". Una compraventa no se renueva, no
-- tiene plazo y no tiene renta. Son dos hechos distintos.
--
-- LO QUE ESTA MIGRACION NO HACE, Y ES DELIBERADO
--   - No toca `contrato_alquiler` ni `comision_liquidacion`: el ciclo de
--     alquiler no cambia.
--   - No anade un codigo VENDIDO a `propiedad.disponibilidad_comercial`. Ese
--     vocabulario esta gobernado por `EstadosDominio.DisponibilidadComercial`,
--     por `docs/ai/matriz-codigos-estado.md` y por el catalogo de productores;
--     anadirlo es una decision aparte. Mientras tanto el cierre de venta marca
--     `T` (retirado del mercado), que es cierto y mas debil, y el HECHO de que
--     se vendio queda en `contrato_compraventa`, en el hito 'C' y en
--     `captacion.motivo_cierre = 'V'`.
--   - No borra ni reinterpreta ninguna fila existente.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. La mesa de negociacion.
--
-- Cuelga de la OPORTUNIDAD y no del encargo a secas: el encargo dice que se
-- vende, la oportunidad dice CON QUIEN se esta negociando. Dos interesados por
-- el mismo inmueble son dos oportunidades y dos cadenas de ofertas separadas;
-- colgarlas solo del encargo las mezclaria en una sola linea y ninguna lectura
-- podria volver a separarlas.
--
-- `id_captacion` se guarda ademas de poder deducirse por la oportunidad, y no
-- es redundancia gratuita: es lo que permite leer la serie economica de un
-- encargo sin pasar por la mesa, y lo que un trigger usa para exigir que las
-- dos coincidan.
-- ---------------------------------------------------------------------
CREATE TABLE oferta (
    id_oferta            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id      BIGINT        NOT NULL REFERENCES organizacion (id_organizacion),
    id_oportunidad       BIGINT        NOT NULL,
    id_captacion         BIGINT        NOT NULL,

    -- Numero de vuelta dentro de ESTA mesa. Empieza en 1 y no se reutiliza:
    -- una contraoferta es la ronda siguiente, no una correccion de la anterior.
    ronda                INT           NOT NULL,

    -- 'I' la presento el INTERESADO, 'P' el PROPIETARIO (la contraoferta).
    -- No se deduce de la ronda: una negociacion puede empezar por cualquiera
    -- de los dos lados, y deducirlo seria inventar quien hablo primero.
    presentada_por       VARCHAR(1)    NOT NULL,

    monto                NUMERIC(14,2) NOT NULL,
    moneda               VARCHAR(3)    NOT NULL,

    -- 'P' presentada (viva), 'A' aceptada, 'R' rechazada,
    -- 'S' superada por una contraoferta, 'T' retirada por quien la presento.
    estado               VARCHAR(1)    NOT NULL,

    -- Lo pactado ademas del importe: plazo de pago, muebles incluidos, quien
    -- asume gastos notariales. Texto libre a proposito: nadie ha inventariado
    -- las condiciones reales de una compraventa en este mercado, y un
    -- vocabulario cerrado hoy seria arbitrario u obligaria a mentir.
    condiciones          VARCHAR(500),

    fecha                DATE          NOT NULL,

    -- Quien la registro (persona_rol). No es quien la ofrecio: la ofrece el
    -- interesado o el propietario, y `presentada_por` lo dice. Esto es el
    -- responsable del asiento.
    id_rol_registra      BIGINT        NOT NULL,

    -- Por donde entro la peticion que produjo la fila: SPA, WHATSAPP, API o
    -- SISTEMA. Mismo vocabulario que `evento_dominio.canal` (V59).
    origen               VARCHAR(10)   NOT NULL,

    -- ---------------------------------------------------------------
    -- La REFERENCIA congelada (D-N-1): contra que precio se ofrecio.
    --
    -- Se congela al presentar y no se recalcula: un anuncio que baja de precio
    -- una semana despues no puede cambiar retroactivamente el descuento con el
    -- que se negocio. Se guarda CUAL se uso —'P' publicado, 'U' autorizado—
    -- porque no son lo mismo: uno es lo que el mercado vio, el otro lo que el
    -- propietario autorizo.
    --
    -- Los cuatro campos van juntos o no va ninguno. Si el encargo no tiene ni
    -- 'P' ni 'U', la referencia es FALTANTE y la ficha lo dice; NO se rellena
    -- con el importe del encargo ni con el de la oferta.
    -- ---------------------------------------------------------------
    hito_referencia      VARCHAR(1),
    id_precio_referencia BIGINT        REFERENCES precio_propiedad (id_precio),
    monto_referencia     NUMERIC(14,2),
    moneda_referencia    VARCHAR(3),

    fecha_creacion       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ,

    CONSTRAINT ck_oferta_estado          CHECK (estado IN ('P', 'A', 'R', 'S', 'T')),
    CONSTRAINT ck_oferta_presentada_por  CHECK (presentada_por IN ('I', 'P')),
    CONSTRAINT ck_oferta_moneda          CHECK (moneda IN ('PEN', 'USD')),
    CONSTRAINT ck_oferta_monto           CHECK (monto > 0),
    CONSTRAINT ck_oferta_ronda           CHECK (ronda >= 1),
    CONSTRAINT ck_oferta_origen          CHECK (origen IN ('SPA', 'WHATSAPP', 'API', 'SISTEMA')),
    CONSTRAINT ck_oferta_hito_referencia CHECK (hito_referencia IS NULL
                                                OR hito_referencia IN ('P', 'U')),
    CONSTRAINT ck_oferta_moneda_referencia CHECK (moneda_referencia IS NULL
                                                OR moneda_referencia IN ('PEN', 'USD')),
    -- La referencia entera, o ninguna. Un monto sin su moneda, o una moneda sin
    -- el hito del que salio, es media referencia y no se puede interpretar.
    CONSTRAINT ck_oferta_referencia_completa CHECK (
        (hito_referencia IS NULL AND id_precio_referencia IS NULL
         AND monto_referencia IS NULL AND moneda_referencia IS NULL)
        OR (hito_referencia IS NOT NULL AND id_precio_referencia IS NOT NULL
            AND monto_referencia IS NOT NULL AND moneda_referencia IS NOT NULL)),

    -- Una sola oferta por ronda y mesa: dos filas con la ronda 3 no dicen quien
    -- respondio a quien.
    CONSTRAINT uq_oferta_ronda UNIQUE (id_oportunidad, ronda),
    CONSTRAINT uq_oferta_org   UNIQUE (organizacion_id, id_oferta),
    -- Para la FK compuesta de precio_propiedad: un hito solo puede apuntar a
    -- una oferta DEL MISMO encargo.
    CONSTRAINT uq_oferta_encargo UNIQUE (id_captacion, id_oferta),

    CONSTRAINT fk_oferta_oportunidad_org FOREIGN KEY (organizacion_id, id_oportunidad)
        REFERENCES oportunidad_comercial (organizacion_id, id_oportunidad),
    CONSTRAINT fk_oferta_captacion_org FOREIGN KEY (organizacion_id, id_captacion)
        REFERENCES captacion (organizacion_id, id_captacion),
    CONSTRAINT fk_oferta_registra_org FOREIGN KEY (organizacion_id, id_rol_registra)
        REFERENCES persona_rol (organizacion_id, id_persona_rol)
);

COMMENT ON TABLE oferta IS
    'Cada vuelta de una negociacion: quien ofrecio, cuanto, contra que precio de '
    'referencia y como acabo. Cuelga de la oportunidad (con quien se negocia) y del '
    'encargo (sobre que). WP-A, D-N-2.';

COMMENT ON COLUMN oferta.presentada_por IS
    'I el interesado, P el propietario (la contraoferta). No se deduce de la ronda.';
COMMENT ON COLUMN oferta.estado IS
    'P presentada (viva), A aceptada, R rechazada, S superada por contraoferta, '
    'T retirada por quien la presento.';
COMMENT ON COLUMN oferta.hito_referencia IS
    'Contra que precio se ofrecio: P el ultimo publicado del encargo, U el ultimo '
    'autorizado si no habia anuncio. NULL = el encargo no tenia ninguno de los dos y '
    'la referencia es FALTANTE. Nunca se rellena con otra cifra.';
COMMENT ON COLUMN oferta.condiciones IS
    'Lo pactado ademas del importe. Texto libre: las condiciones reales de una '
    'compraventa no estan inventariadas y un vocabulario cerrado hoy seria arbitrario.';
COMMENT ON COLUMN oferta.id_rol_registra IS
    'Quien hizo el asiento, no quien ofrecio. Quien ofrecio lo dice presentada_por.';

-- Una sola oferta ACEPTADA por mesa. Es el invariante de dinero de esta tabla:
-- dos aceptadas significan dos precios de cierre para la misma negociacion, y
-- el contrato no sabria cual firmar. Se resuelve en la BASE y no solo en el
-- servicio porque dos peticiones simultaneas pasan las dos la comprobacion
-- previa y solo el indice corta la carrera.
CREATE UNIQUE INDEX uq_oferta_aceptada_por_oportunidad
    ON oferta (id_oportunidad)
    WHERE estado = 'A';

-- Una sola oferta VIVA por mesa: mientras hay una presentada, la siguiente es
-- una contraoferta que la supera, no una segunda oferta paralela.
CREATE UNIQUE INDEX uq_oferta_viva_por_oportunidad
    ON oferta (id_oportunidad)
    WHERE estado = 'P';

CREATE INDEX ix_oferta_oportunidad ON oferta (organizacion_id, id_oportunidad, ronda DESC);
CREATE INDEX ix_oferta_encargo     ON oferta (organizacion_id, id_captacion, id_oferta DESC);
CREATE INDEX ix_oferta_organizacion ON oferta (organizacion_id);

-- La oferta y su oportunidad tienen que hablar del MISMO encargo. Sin esto, una
-- oferta podia declarar el encargo de otra propiedad y la serie economica de
-- ese encargo se llenaba de cifras de una negociacion ajena.
CREATE OR REPLACE FUNCTION exigir_encargo_de_la_mesa()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    encargo_de_la_mesa bigint;
BEGIN
    SELECT o.id_captacion INTO encargo_de_la_mesa
      FROM oportunidad_comercial o
     WHERE o.id_oportunidad = NEW.id_oportunidad;

    IF encargo_de_la_mesa IS DISTINCT FROM NEW.id_captacion THEN
        RAISE EXCEPTION
            'La oferta declara el encargo % pero su oportunidad negocia el encargo %',
            NEW.id_captacion, encargo_de_la_mesa
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END $$;

CREATE TRIGGER tg_oferta_encargo_de_la_mesa
    BEFORE INSERT OR UPDATE ON oferta
    FOR EACH ROW EXECUTE FUNCTION exigir_encargo_de_la_mesa();

-- ---------------------------------------------------------------------
-- 2. La serie economica aprende a decir de que MESA es cada hito.
--
-- `id_captacion` (V49/V76) responde "de que encargo". Con dos interesados
-- negociando el mismo inmueble a la vez eso ya no basta: los dos escriben hitos
-- 'O' del mismo encargo y sin esta columna quedan mezclados en una sola linea
-- que nadie puede volver a separar.
--
-- Nullable, y no es un hueco: los hitos 'U' (autorizado) y 'P' (publicado) NO
-- salen de ninguna mesa —salen del encargo y de su anuncio—, asi que para ellos
-- la respuesta correcta es «ninguna».
--
-- La FK es COMPUESTA con `id_captacion` a proposito: un hito no puede apuntar a
-- una oferta de otro encargo. Va MATCH SIMPLE (el defecto), asi que las filas
-- historicas con `id_oferta` NULL no se comprueban y no hay que tocarlas.
-- ---------------------------------------------------------------------
ALTER TABLE precio_propiedad
    ADD COLUMN IF NOT EXISTS id_oferta BIGINT;

ALTER TABLE precio_propiedad
    ADD CONSTRAINT fk_precio_oferta_del_encargo
    FOREIGN KEY (id_captacion, id_oferta)
    REFERENCES oferta (id_captacion, id_oferta);

COMMENT ON COLUMN precio_propiedad.id_oferta IS
    'De que vuelta de que negociacion sale este hito. NULL en U y P, que no nacen de '
    'ninguna mesa, y en todo lo anterior a V90. WP-A, D-N-2.';

CREATE INDEX ix_precio_propiedad_oferta
    ON precio_propiedad (id_oferta)
    WHERE id_oferta IS NOT NULL;

-- ---------------------------------------------------------------------
-- 3. El cierre de una VENTA.
--
-- Guarda el vinculo (encargo, mesa, oferta aceptada, comprador, inmueble) y las
-- DOS cifras que una compraventa tiene y un alquiler no:
--
--   monto_pactado    lo que de verdad se acordo. Sale de la oferta aceptada
--                    salvo ajuste explicito en el mismo acto de cierre.
--   monto_declarado  lo que consta en la escritura, cuando difiere. OPCIONAL y
--                    FALTANTE por defecto: igualarlo al pactado seria inventar
--                    un dato registral que nadie ha leido.
--
-- SIN columna `estado`, y es deliberado: una compraventa no tiene ciclo —no se
-- renueva, no vence, no se rescinde por plazo—. Los hitos registrales (minuta,
-- escritura, bloqueo, partida) ya viven en `condicion_compraventa` (V51). Una
-- columna de estado sin operacion que la produzca seria vocabulario huerfano,
-- que es justo lo que el catalogo de productores existe para impedir.
-- ---------------------------------------------------------------------
CREATE TABLE contrato_compraventa (
    id_contrato_compraventa BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id         BIGINT        NOT NULL REFERENCES organizacion (id_organizacion),
    id_oportunidad          BIGINT        NOT NULL,
    id_captacion            BIGINT        NOT NULL,
    id_propiedad            BIGINT        NOT NULL,
    id_oferta               BIGINT        NOT NULL,

    -- El comprador, congelado. Es el cliente de la oportunidad en el momento
    -- del cierre; no se relee de la cadena viva por la misma razon que V27
    -- congelo la atribucion del alquiler.
    id_rol_cliente          BIGINT        NOT NULL,
    id_rol_agente_cierre    BIGINT        NOT NULL,
    id_rol_broker_cierre    BIGINT,

    monto_pactado           NUMERIC(14,2) NOT NULL,
    moneda                  VARCHAR(3)    NOT NULL,
    monto_declarado         NUMERIC(14,2),
    moneda_declarada        VARCHAR(3),

    fecha_firma             DATE          NOT NULL,
    observaciones           TEXT,
    fecha_creacion          TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_compraventa_monto     CHECK (monto_pactado > 0),
    CONSTRAINT ck_compraventa_moneda_pactada CHECK (moneda IN ('PEN', 'USD')),
    CONSTRAINT ck_compraventa_declarado CHECK (monto_declarado IS NULL OR monto_declarado > 0),
    -- Un importe declarado sin su moneda no se puede comparar con el pactado, y
    -- suponer que van en la misma es exactamente la inferencia que se prohibe:
    -- en este mercado se pacta en dolares y se escritura en soles a menudo.
    CONSTRAINT ck_compraventa_declarado_completo CHECK (
        (monto_declarado IS NULL AND moneda_declarada IS NULL)
        OR (monto_declarado IS NOT NULL AND moneda_declarada IS NOT NULL)),
    CONSTRAINT ck_compraventa_moneda_declarada CHECK (
        moneda_declarada IS NULL OR moneda_declarada IN ('PEN', 'USD')),

    -- Un cierre por mesa y un cierre por oferta: la oferta aceptada se firma
    -- una sola vez.
    CONSTRAINT uq_compraventa_oportunidad UNIQUE (id_oportunidad),
    CONSTRAINT uq_compraventa_oferta      UNIQUE (id_oferta),
    CONSTRAINT uq_compraventa_org         UNIQUE (organizacion_id, id_contrato_compraventa),

    CONSTRAINT fk_compraventa_oportunidad_org FOREIGN KEY (organizacion_id, id_oportunidad)
        REFERENCES oportunidad_comercial (organizacion_id, id_oportunidad),
    CONSTRAINT fk_compraventa_captacion_org FOREIGN KEY (organizacion_id, id_captacion)
        REFERENCES captacion (organizacion_id, id_captacion),
    CONSTRAINT fk_compraventa_propiedad_org FOREIGN KEY (organizacion_id, id_propiedad)
        REFERENCES propiedad (organizacion_id, id_propiedad),
    CONSTRAINT fk_compraventa_oferta_org FOREIGN KEY (organizacion_id, id_oferta)
        REFERENCES oferta (organizacion_id, id_oferta),
    CONSTRAINT fk_compraventa_cliente_org FOREIGN KEY (organizacion_id, id_rol_cliente)
        REFERENCES persona_rol (organizacion_id, id_persona_rol),
    CONSTRAINT fk_compraventa_agente_org FOREIGN KEY (organizacion_id, id_rol_agente_cierre)
        REFERENCES persona_rol (organizacion_id, id_persona_rol),
    CONSTRAINT fk_compraventa_broker_org FOREIGN KEY (organizacion_id, id_rol_broker_cierre)
        REFERENCES persona_rol (organizacion_id, id_persona_rol)
);

COMMENT ON TABLE contrato_compraventa IS
    'El cierre de una venta: encargo, mesa, oferta aceptada, comprador, importe pactado '
    'y -si difiere- el declarado en la escritura. WP-A, D-N-3.';

COMMENT ON COLUMN contrato_compraventa.monto_pactado IS
    'Lo que de verdad se acordo. Sale de la oferta aceptada salvo ajuste explicito.';
COMMENT ON COLUMN contrato_compraventa.monto_declarado IS
    'Lo que consta en la escritura, SOLO si difiere del pactado. NULL = no se declaro; '
    'nunca se rellena igualandolo al pactado.';
COMMENT ON COLUMN contrato_compraventa.id_rol_agente_cierre IS
    'Agente al que se atribuye el cierre. Congelado; no sigue reasignaciones posteriores.';

CREATE INDEX ix_compraventa_organizacion ON contrato_compraventa (organizacion_id);
CREATE INDEX ix_compraventa_encargo
    ON contrato_compraventa (organizacion_id, id_captacion, id_contrato_compraventa DESC);
CREATE INDEX ix_compraventa_agente
    ON contrato_compraventa (organizacion_id, id_rol_agente_cierre, id_contrato_compraventa DESC);

-- El cierre de venta cierra un encargo de VENTA. Un encargo de alquiler se
-- cierra con su contrato de alquiler, y confundirlos meteria un importe de
-- compraventa en la estadistica de rentas.
CREATE OR REPLACE FUNCTION exigir_encargo_de_venta()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    operacion_encargo varchar(1);
BEGIN
    SELECT c.motivo_operacion INTO operacion_encargo
      FROM captacion c
     WHERE c.id_captacion = NEW.id_captacion;

    IF operacion_encargo IS DISTINCT FROM 'V' THEN
        RAISE EXCEPTION
            'Un contrato de compraventa cierra un encargo de VENTA; el % es de operacion %',
            NEW.id_captacion, coalesce(operacion_encargo, 'desconocida')
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END $$;

CREATE TRIGGER tg_compraventa_encargo_de_venta
    BEFORE INSERT OR UPDATE ON contrato_compraventa
    FOR EACH ROW EXECUTE FUNCTION exigir_encargo_de_venta();

-- ---------------------------------------------------------------------
-- 4. La oferta entra en la auditoria universal.
--
-- Su estado es una maquina real (P -> A|R|S|T) y toda transicion pasa por
-- `Transiciones`, que escribe en `historial_estado`. Esa tabla tiene FK a
-- `entidad_tipo`, asi que sin esta fila la primera aceptacion reventaria con
-- una violacion de clave ajena.
-- ---------------------------------------------------------------------
INSERT INTO entidad_tipo (codigo, descripcion, auditable, referenciable)
VALUES ('OFERTA', 'Oferta de una negociacion', TRUE, TRUE)
ON CONFLICT (codigo) DO NOTHING;

-- ---------------------------------------------------------------------
-- 5. Por que se cae una VENTA.
--
-- `motivo_no_continuidad` nacio con el vocabulario de un alquiler: precio,
-- ubicacion, condiciones del contrato, local no adecuado, cliente no responde,
-- encontro otra opcion, otro. Las tres razones por las que de verdad se cae una
-- compraventa no estan: el banco no aprobo el credito, la propiedad no se pudo
-- sanear registralmente, el propietario se echo atras. Y "desistio" no es
-- "no responde": uno decidio que no, del otro no se sabe nada.
--
-- Sin estas cuatro, el agente esta obligado a marcar 'O' (otro) y el analisis
-- de por que se pierden las ventas no se puede hacer. Se anaden al CHECK
-- existente; ninguna fila cambia.
-- ---------------------------------------------------------------------
ALTER TABLE motivo_no_continuidad
    DROP CONSTRAINT ck_motivo_razon;

ALTER TABLE motivo_no_continuidad
    ADD CONSTRAINT ck_motivo_razon
    CHECK (razon_principal IN ('P', 'U', 'C', 'L', 'N', 'E', 'O',
                               'F', 'T', 'D', 'S'));

COMMENT ON COLUMN motivo_no_continuidad.razon_principal IS
    'P precio, U ubicacion, C condiciones del contrato, L local no adecuado, '
    'N cliente no responde, E encontro otra opcion, F no consiguio financiamiento, '
    'T el propietario retiro el inmueble, D no se resolvio la documentacion, '
    'S el interesado desistio, O otro. Los cuatro ultimos entraron con V90 porque '
    'una venta se cae por razones que el vocabulario de alquiler no sabia decir.';

-- ---------------------------------------------------------------------
-- 6. Las guardas. Cuentan lo que hay en vez de repetir una cifra escrita a mano.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    razones      int;
    checks_venta int;
    tipo_oferta  int;
BEGIN
    SELECT count(*) INTO razones
      FROM pg_constraint
     WHERE conname = 'ck_motivo_razon'
       AND pg_get_constraintdef(oid) LIKE '%''F''%'
       AND pg_get_constraintdef(oid) LIKE '%''T''%'
       AND pg_get_constraintdef(oid) LIKE '%''D''%'
       AND pg_get_constraintdef(oid) LIKE '%''S''%';
    IF razones <> 1 THEN
        RAISE EXCEPTION 'V90: ck_motivo_razon no admite las cuatro razones nuevas';
    END IF;

    SELECT count(*) INTO checks_venta
      FROM pg_class
     WHERE relname IN ('oferta', 'contrato_compraventa')
       AND relkind = 'r';
    IF checks_venta <> 2 THEN
        RAISE EXCEPTION 'V90: faltan tablas de la negociacion (encontradas %)', checks_venta;
    END IF;

    SELECT count(*) INTO tipo_oferta FROM entidad_tipo WHERE codigo = 'OFERTA';
    IF tipo_oferta <> 1 THEN
        RAISE EXCEPTION 'V90: entidad_tipo OFERTA no quedo sembrado';
    END IF;

    RAISE NOTICE 'V90: oferta + contrato_compraventa + precio_propiedad.id_oferta listos';
END $$;
