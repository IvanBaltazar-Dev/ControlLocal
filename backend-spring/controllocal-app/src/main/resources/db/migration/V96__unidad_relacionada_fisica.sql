-- =====================================================================
-- V96 - Relacion fisica generica entre propiedades
--
-- Una unidad con identidad propia vive en propiedad. Esta tabla conserva
-- unicamente la relacion fisica entre dos propiedades y su vigencia.
-- El conjunto comercial de oferta/cierre queda fuera de este corte.
-- =====================================================================

CREATE TABLE unidad_relacionada (
    id_unidad_relacionada  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id        BIGINT NOT NULL,
    id_propiedad_principal BIGINT NOT NULL,
    id_propiedad_relacionada BIGINT NOT NULL,
    tipo_relacion           VARCHAR(1) NOT NULL,
    vigente_desde           DATE NOT NULL,
    vigente_hasta           DATE,
    fecha_actualizacion     TIMESTAMPTZ,

    CONSTRAINT uq_unidad_relacionada_org
        UNIQUE (organizacion_id, id_unidad_relacionada),
    CONSTRAINT fk_unidad_relacionada_organizacion
        FOREIGN KEY (organizacion_id)
        REFERENCES organizacion (id_organizacion),
    CONSTRAINT fk_unidad_relacionada_principal
        FOREIGN KEY (organizacion_id, id_propiedad_principal)
        REFERENCES propiedad (organizacion_id, id_propiedad),
    CONSTRAINT fk_unidad_relacionada_destino
        FOREIGN KEY (organizacion_id, id_propiedad_relacionada)
        REFERENCES propiedad (organizacion_id, id_propiedad),
    CONSTRAINT ck_unidad_relacionada_no_auto
        CHECK (id_propiedad_principal <> id_propiedad_relacionada),
    CONSTRAINT ck_unidad_relacionada_tipo
        CHECK (tipo_relacion IN ('A', 'I', 'C')),
    CONSTRAINT ck_unidad_relacionada_vigencia
        CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

COMMENT ON TABLE unidad_relacionada IS
    'Relacion fisica generica entre dos propiedades del mismo tenant. No es un paquete comercial.';
COMMENT ON COLUMN unidad_relacionada.tipo_relacion IS
    'A accesoria, I independiente con partida propia, C vinculada por reglamento interno.';
COMMENT ON COLUMN unidad_relacionada.vigente_hasta IS
    'NULL significa que la relacion sigue vigente; la fila historica no se borra.';

CREATE INDEX ix_unidad_relacionada_principal
    ON unidad_relacionada (organizacion_id, id_propiedad_principal, vigente_desde, id_unidad_relacionada);
CREATE INDEX ix_unidad_relacionada_destino
    ON unidad_relacionada (organizacion_id, id_propiedad_relacionada, vigente_desde, id_unidad_relacionada);

-- Un mismo par fisico no puede estar vigente dos veces, incluso si un cliente
-- intenta invertir principal/relacionada. Las relaciones cerradas se conservan
-- para trazabilidad y pueden repetirse en el tiempo con una nueva vigencia.
CREATE UNIQUE INDEX uq_unidad_relacionada_vigente
    ON unidad_relacionada (
        organizacion_id,
        LEAST(id_propiedad_principal, id_propiedad_relacionada),
        GREATEST(id_propiedad_principal, id_propiedad_relacionada)
    )
    WHERE vigente_hasta IS NULL;

CREATE OR REPLACE FUNCTION validar_unidad_relacionada()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.tipo_relacion = 'I'
       AND NOT EXISTS (
           SELECT 1
             FROM propiedad p
            WHERE p.organizacion_id = NEW.organizacion_id
              AND p.id_propiedad = NEW.id_propiedad_relacionada
              AND p.partida_registral IS NOT NULL
       ) THEN
        RAISE EXCEPTION
            'Una unidad independiente exige que la propiedad relacionada tenga partida registral.'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER tg_unidad_relacionada_partida
    BEFORE INSERT OR UPDATE ON unidad_relacionada
    FOR EACH ROW EXECUTE FUNCTION validar_unidad_relacionada();

-- La guarda tambien protege la operacion inversa: una propiedad que sostiene
-- una relacion independiente vigente no puede perder silenciosamente la
-- partida que hace valida esa independencia.
CREATE OR REPLACE FUNCTION proteger_partida_de_unidad_independiente()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.partida_registral IS NULL
       AND OLD.partida_registral IS NOT NULL
       AND EXISTS (
           SELECT 1
             FROM unidad_relacionada u
            WHERE u.organizacion_id = NEW.organizacion_id
              AND u.id_propiedad_relacionada = NEW.id_propiedad
              AND u.tipo_relacion = 'I'
              AND u.vigente_hasta IS NULL
       ) THEN
        RAISE EXCEPTION
            'No se puede retirar la partida de una unidad independiente vigente.'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER tg_propiedad_partida_unidad_independiente
    BEFORE UPDATE OF partida_registral ON propiedad
    FOR EACH ROW EXECUTE FUNCTION proteger_partida_de_unidad_independiente();

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
          FROM unidad_relacionada
         WHERE id_propiedad_principal = id_propiedad_relacionada
    ) THEN
        RAISE EXCEPTION 'V96: existen relaciones fisicas consigo mismas.';
    END IF;
END $$;
