CREATE UNIQUE INDEX uq_borrador_contexto ON borrador_captura (organizacion_id, id_borrador);
CREATE TABLE operacion_herramienta (
    id_operacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES organizacion(id_organizacion),
    referencia VARCHAR(36) NOT NULL UNIQUE,
    id_persona BIGINT NOT NULL REFERENCES persona(id_persona),
    id_persona_rol BIGINT NOT NULL REFERENCES persona_rol(id_persona_rol),
    rol_efectivo VARCHAR(30) NOT NULL,
    identidad_sesion VARCHAR(64) NOT NULL,
    id_borrador BIGINT NOT NULL,
    capacidad VARCHAR(60) NOT NULL CHECK (capacidad = 'confirmar_captura'),
    huella VARCHAR(64) NOT NULL CHECK (huella ~ '^[0-9a-f]{64}$'),
    contenido TEXT NOT NULL CHECK (jsonb_typeof(contenido::jsonb) = 'object'),
    procedencia TEXT NOT NULL CHECK (jsonb_typeof(procedencia::jsonb) = 'object'),
    caduca_en TIMESTAMP WITH TIME ZONE NOT NULL,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    prueba_revision VARCHAR(64),
    evento_humano VARCHAR(64),
    confirmada_en TIMESTAMP WITH TIME ZONE,
    version_aprobada BIGINT,
    aprobacion TEXT CHECK (aprobacion IS NULL OR jsonb_typeof(aprobacion::jsonb) = 'object'),
    estado VARCHAR(1) NOT NULL DEFAULT 'P' CHECK (estado IN ('P','I','X','R','U')),
    resultado TEXT CHECK (resultado IS NULL OR jsonb_typeof(resultado::jsonb) = 'object'),
    motivo VARCHAR(60),
    version BIGINT NOT NULL DEFAULT 0,
    FOREIGN KEY (organizacion_id, id_borrador) REFERENCES borrador_captura(organizacion_id, id_borrador),
    CHECK ((estado = 'P' AND evento_humano IS NULL AND confirmada_en IS NULL)
        OR (estado <> 'P' AND evento_humano IS NOT NULL AND confirmada_en IS NOT NULL)),
    CHECK (estado <> 'P' OR (version_aprobada IS NULL AND aprobacion IS NULL)),
    CHECK (estado = 'P' OR (version_aprobada IS NOT NULL AND aprobacion IS NOT NULL)),
    CHECK (estado <> 'X' OR resultado IS NOT NULL),
    CHECK (caduca_en > creada_en)
);
CREATE INDEX ix_operacion_actor ON operacion_herramienta(organizacion_id, id_persona_rol, referencia);
